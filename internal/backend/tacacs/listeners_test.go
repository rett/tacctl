// "config listen: a change restarts tacquito after a reload, and show
// names tacctl.yaml"; "drop-in: one settings change renders every flag of
// the default listener".
func TestListenerSetDefault(t *testing.T) {
	e := newTenv(t).withStore("store.multiscope.yaml")
	ctx := context.Background()
	if err := e.b.Listeners().Set(ctx, "default", "tcp", "10.1.0.1:49"); err != nil {
		t.Fatalf("%v\n%s", err, e.stderr)
	}
	mustContain(t, e.stdout.String(), "Listener changed to tcp 10.1.0.1:49. Service restarted.")
	var order []string
	for _, a := range e.run.Argvs() {
		if regexp.MustCompile(`^systemctl (daemon-reload|restart tacquito|is-active --quiet tacquito)$`).MatchString(a) {
			order = append(order, a)
		}
	}
	if !slices.Equal(order, []string{"systemctl daemon-reload", "systemctl restart tacquito", "systemctl is-active --quiet tacquito"}) {
		t.Fatal(e.run.Argvs())
	}
	dropin := e.dropIn("default")
	text := readFile(t, dropin)
	if !strings.HasPrefix(text, "# GENERATED by tacctl from tacctl.yaml") {
		t.Fatal(text)
	}
	for _, l := range []string{"[Service]", `Environment="TACQUITO_NETWORK=tcp"`, `Environment="TACQUITO_ADDRESS=10.1.0.1:49"`,
		`Environment="TACQUITO_LEVEL=20"`, `Environment="TACQUITO_METRICS_ADDRESS=127.0.0.1:8080"`,
		`Environment="TACQUITO_ACCT_LOG=` + e.p.Log + `/accounting.log"`} {
		mustLine(t, text, l)
	}
	if st, _ := os.Stat(dropin); st.Mode().Perm() != 0o644 {
		t.Fatalf("mode %v", st.Mode())
	}
	mustContain(t, readFile(t, e.p.Overrides), "address: 10.1.0.1:49")
	if exists(e.b.overrideFile()) || !e.recorded(dropin) {
		t.Fatal("hand-managed drop-in written, or the rendered one not recorded")
	}
	s := show(t, e, "")
	mustLine(t, s, "  Current listener: tcp 10.1.0.1:49")
	mustLine(t, s, "  (override in "+e.p.Overrides+")")
	// "config listen: with a store the change is snapshotted first".
	mustContain(t, e.stdout.String(), "Config snapshot saved to")
	if len(e.snapshots()) != 1 {
		t.Fatal(e.snapshots())
	}
	e.reset()
	if err := e.b.Listeners().Set(ctx, "", "tcp", "10.1.0.1:49"); err != nil {
		t.Fatal(err)
	}
	mustContain(t, e.stdout.String(), "Already listening on tcp 10.1.0.1:49.")
	if len(e.run.Calls()) != 0 {
		t.Fatal(e.run.Argvs())
	}
	e.noKeep()
}

// "config listen: a bad address is refused before anything is written",
// "config listen: rejects unknown subcommand", and the listeners verb
// growing no 'list' (tests/unit/backend.bats).
func TestListenerSetRefusesBadInput(t *testing.T) {
	e := newTenv(t).withStore("store.multiscope.yaml")
	ctx := context.Background()
	for _, c := range []struct{ net, addr, msg string }{
		{"tcp", "10.1.0.1", "Invalid tcp address: '10.1.0.1'"},
		{"tcp", "[::1]:49", "Invalid tcp address"},
		{"tcp6", "10.1.0.1:49", "Invalid tcp6 address"},
		{"tcp", ":0", "Invalid tcp address"},
		{"tcp", "example.net:49", "Invalid tcp address"},
		{"tcp", "", "Missing address. Example: tacctl config listen tcp :49"},
		{"udp", ":49", "Invalid subcommand: 'udp'. Use: show, tcp, tcp6, or reset"},
		{"list", "", "Invalid subcommand: 'list'. Use: show, tcp, tcp6, or reset"},
		{"bogus", "", "Invalid subcommand: 'bogus'"},
	} {
		e.reset()
		err := e.b.Listeners().Set(ctx, "default", c.net, c.addr)
		wantCode(t, err, 1)
		mustContain(t, e.stderr.String(), c.msg)
	}
	if exists(e.p.Overrides) || exists(e.dropIn("default")) || len(e.run.Calls()) != 0 || len(e.snapshots()) != 0 {
		t.Fatal("something was written")
	}
}

// "config listen: tcp6 asks first, and 'n' changes nothing".
func TestListenerSetTCP6Asks(t *testing.T) {
	e := newTenv(t).withStore("store.multiscope.yaml")
	ctx := context.Background()
	e.stdin("n\n")
	if err := e.b.Listeners().Set(ctx, "default", "tcp6", "[::]:49"); err != nil {
		t.Fatal(err)
	}
	mustContain(t, e.stdout.String(), "tcp6 enables dual-stack sockets")
	mustContain(t, e.stdout.String(), "Aborted.")
	if exists(e.p.Overrides) || exists(e.dropIn("default")) {
		t.Fatal("written")
	}
	e.reset()
	e.stdin("y\n")
	if err := e.b.Listeners().Set(ctx, "default", "tcp6", "[::]:49"); err != nil {
		t.Fatal(err)
	}
	mustContain(t, e.stdout.String(), "Listener changed to tcp6 [::]:49.")
	if envOf(t, e.dropIn("default"), "TACQUITO_NETWORK") != "tcp6" || envOf(t, e.dropIn("default"), "TACQUITO_ADDRESS") != "[::]:49" {
		t.Fatal(readFile(t, e.dropIn("default")))
	}
	// Already tcp6: no question.
	e.reset()
	e.stdin("")
	if err := e.b.Listeners().Set(ctx, "default", "tcp6", "[::]:4949"); err != nil {
		t.Fatal(err)
	}
	mustNotContain(t, e.stdout.String(), "dual-stack")
}

// "config listen: reset says what it always said, and goes back to the
// default"; config_setters.bats "config listen reset: clears override".
func TestListenerResetDefault(t *testing.T) {
	e := newTenv(t).withStore("store.multiscope.yaml")
	ctx := context.Background()
	if err := e.b.Listeners().Reset(ctx, ""); err != nil {
		t.Fatal(err)
	}
	mustContain(t, e.stdout.String(), "No listener override set. Already on template default (tcp :49).")
	if err := e.b.Listeners().Set(ctx, "default", "tcp", "10.1.0.1:49"); err != nil {
		t.Fatal(err)
	}
	e.reset()
	if err := e.b.Listeners().Reset(ctx, "default"); err != nil {
		t.Fatal(err)
	}
	mustContain(t, e.stdout.String(), "Listener override removed. Using template default. Service restarted.")
	mustLine(t, readFile(t, e.dropIn("default")), `Environment="TACQUITO_ADDRESS=:49"`)
	if exists(e.p.Overrides) && strings.Contains(readFile(t, e.p.Overrides), "listeners") {
		t.Fatal("listeners left in tacctl.yaml")
	}
	// A reset whose unit does not come up.
	if err := e.b.Listeners().Set(ctx, "default", "tcp", "10.1.0.1:49"); err != nil {
		t.Fatal(err)
	}
	e.reset()
	e.failActive(`tacquito$`)
	err := e.b.Listeners().Reset(ctx, "default")
	wantCode(t, err, 1)
	mustContain(t, e.stderr.String(), "tacquito failed to start after reset.")
}

// "config listen: a unit that does not come up gets the previous settings
// back".
func TestListenerSetUnitThatDoesNotComeUpIsPutBack(t *testing.T) {
	e := newTenv(t).withStore("store.multiscope.yaml")
	ctx := context.Background()
	if err := e.b.Listeners().Set(ctx, "default", "tcp", "10.1.0.1:49"); err != nil {
		t.Fatal(err)
	}
	before := state(e.dropIn("default"), e.p.Overrides, e.p.Rendered)
	e.reset()
	e.failActive(`tacquito$`)
	err := e.b.Listeners().Set(ctx, "default", "tcp", "10.9.9.9:49")
	wantCode(t, err, 1)
	mustContain(t, e.stderr.String(), "tacquito failed to start. Restoring previous override.")
	if state(e.dropIn("default"), e.p.Overrides, e.p.Rendered) != before {
		t.Fatal("not put back")
	}
	// Reload and restart twice: with the new address, then the old one.
	if n := e.countCalls(`^systemctl restart tacquito$`); n != 2 {
		t.Fatalf("restarts %d: %v", n, e.run.Argvs())
	}
	if n := e.countCalls(`^systemctl daemon-reload$`); n != 2 {
		t.Fatalf("reloads %d", n)
	}
	if v, _ := e.env.Conf.Get("listeners.tacacs.default.address", ""); v != "10.1.0.1:49" {
		t.Fatalf("the view was not reloaded: %q", v)
	}
	e.noKeep()
}

