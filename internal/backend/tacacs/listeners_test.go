// The listeners verb and 'tacctl config listen' below its argument parsing
// (tests/integration/listeners.bats, tests/unit/backend.bats "tacacs
// listeners", tests/integration/config_setters.bats "config listen"), with
// systemctl scripted as the bats stub does. The flag parsing, the usage
// block and the backend/listener-name checks are internal/cli's (WP2.4c).

func lines(ls []backend.Listener) []string {
	var out []string
	for _, l := range ls {
		out = append(out, l.Name+" "+l.Network+" "+l.Address)
	}
	return out
}

func list(t *testing.T, e *tenv) []string {
	t.Helper()
	ls, err := e.b.Listeners().List()
	if err != nil {
		t.Fatal(err)
	}
	return lines(ls)
}

func show(t *testing.T, e *tenv, name string) string {
	t.Helper()
	s, err := e.b.Listeners().Show(context.Background(), name)
	if err != nil {
		t.Fatalf("show %s: %v\n%s", name, err, e.stderr)
	}
	return s
}

// "tacacs listeners list: the built-in default, then what tacctl.yaml says".
func TestListenersList(t *testing.T) {
	e := newTenv(t)
	if got := list(t, e); !slices.Equal(got, []string{"default tcp :49"}) {
		t.Fatal(got)
	}
	// A tacctl.yaml that names no listener is not parsed (an unparsable one
	// warns nothing here).
	e.writeOverrides("password: [unterminated\n")
	if got := list(t, e); !slices.Equal(got, []string{"default tcp :49"}) || e.stderr.Len() != 0 {
		t.Fatal(got, e.stderr)
	}
	e.writeOverrides("listeners:\n  tacacs:\n    default: {network: tcp6, address: '[::]:4949'}\n    zeta: {address: '127.0.0.1:4951'}\n    alpha: {address: '127.0.0.1:4950'}\n")
	if got := list(t, e); !slices.Equal(got, []string{"default tcp6 [::]:4949", "alpha tcp 127.0.0.1:4950", "zeta tcp 127.0.0.1:4951"}) {
		t.Fatal(got)
	}
}

