// "config listen --listener: adds a listener as its own instance,
// restarting nothing else"; "drop-in: an instance gets its own address,
// accounting log and no reachable metrics".
func TestListenerAddInstance(t *testing.T) {
	e := newTenv(t).withStore("store.multiscope.yaml")
	ctx := context.Background()
	if err := e.b.LogLevel(ctx, "debug"); err != nil {
		t.Fatal(err)
	}
	e.reset()
	if err := e.b.Listeners().Set(ctx, "mgmt", "tcp", "127.0.0.1:4949"); err != nil {
		t.Fatalf("%v\n%s", err, e.stderr)
	}
	mustContain(t, e.stdout.String(), "Listener 'mgmt' added on tcp 127.0.0.1:4949. tacquito@mgmt.service enabled and started.")
	mustContain(t, e.stdout.String(), e.p.Log+"/accounting-mgmt.log")
	for _, re := range []string{`^systemctl daemon-reload$`, `^systemctl enable --quiet tacquito@mgmt\.service$`,
		`^systemctl restart tacquito@mgmt\.service$`, `^systemctl is-active --quiet tacquito@mgmt\.service$`} {
		if !e.called(re) {
			t.Fatalf("no %s: %v", re, e.run.Argvs())
		}
	}
	if e.called(`^systemctl restart tacquito$`) {
		t.Fatal(e.run.Argvs())
	}
	mustContain(t, readFile(t, e.p.Overrides), "mgmt:")
	m := e.dropIn("mgmt")
	for k, v := range map[string]string{"TACQUITO_NETWORK": "tcp", "TACQUITO_ADDRESS": "127.0.0.1:4949", "TACQUITO_LEVEL": "30",
		"TACQUITO_METRICS_ADDRESS": "127.0.0.1:0", "TACQUITO_ACCT_LOG": e.p.Log + "/accounting-mgmt.log"} {
		if got := envOf(t, m, k); got != v {
			t.Fatalf("%s=%q, want %q", k, got, v)
		}
	}
	d := e.dropIn("default")
	if envOf(t, d, "TACQUITO_ADDRESS") != ":49" || envOf(t, d, "TACQUITO_ACCT_LOG") != e.p.Log+"/accounting.log" {
		t.Fatal(readFile(t, d))
	}

	// "config listen --listener: show, change and the flag forms".
	s := show(t, e, "mgmt")
	if s != "  Listener 'mgmt': tcp 127.0.0.1:4949\n  (tacquito@mgmt.service; set in "+e.p.Overrides+")" {
		t.Fatalf("%q", s)
	}
	s = show(t, e, "")
	mustLine(t, s, "  Current listener: tcp :49")
	mustLine(t, s, "  Listener 'mgmt': tcp 127.0.0.1:4949 (tacquito@mgmt.service)")
	e.reset()
	if err := e.b.Listeners().Set(ctx, "mgmt", "tcp", "127.0.0.1:4950"); err != nil {
		t.Fatal(err)
	}
	mustContain(t, e.stdout.String(), "Listener 'mgmt' changed to tcp 127.0.0.1:4950. tacquito@mgmt.service restarted.")
	if e.called(`^systemctl restart tacquito$`) || envOf(t, m, "TACQUITO_ADDRESS") != "127.0.0.1:4950" {
		t.Fatal(e.run.Argvs())
	}
	e.reset()
	_ = e.b.Listeners().Set(ctx, "mgmt", "tcp", "127.0.0.1:4950")
	mustContain(t, e.stdout.String(), "Already listening on tcp 127.0.0.1:4950.")
}

