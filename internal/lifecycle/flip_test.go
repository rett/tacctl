func TestStoreUnflipPutsThePreStoreFileBackAndRemovesTheStore(t *testing.T) {
	e := newTenv(t)
	e.loadFixture("tacquito.minimal.yaml")
	pre := filepath.Join(e.p.BackupDir, "legacy", "tacquito.yaml.pre-store.20200101_000000")
	e.write(pre, fixture(t, "legacy.fresh-install.yaml"), 0o600)
	e.write(e.p.Rendered, "{}\n", 0o600)
	if err := lifecycle.StoreUnflip(e.env, pre); err != nil {
		t.Fatal(err)
	}
	if sha(t, e.p.Config) != sha(t, pre) || mode(t, e.p.Config) != 0o640 || exists(e.p.StoreFile) || exists(e.p.Rendered) ||
		exists(e.p.Config+".tacctl-new") {
		t.Error("state after unflip")
	}
	// Already the same bytes: the file is left as it is (same inode).
	st1, _ := os.Stat(e.p.Config)
	e.write(e.p.StoreFile, "x\n", 0o600)
	if err := lifecycle.StoreUnflip(e.env, pre); err != nil {
		t.Fatal(err)
	}
	st2, _ := os.Stat(e.p.Config)
	if !os.SameFile(st1, st2) || exists(e.p.StoreFile) {
		t.Error("rewritten")
	}
	// A pre-store file that cannot be read: nothing is removed.
	e.write(e.p.StoreFile, "x\n", 0o600)
	if err := lifecycle.StoreUnflip(e.env, filepath.Join(e.w, "missing")); err == nil || !exists(e.p.StoreFile) {
		t.Error("store removed although the config was not replaced")
	}
}

