// of a legacy install into the store, in the order an upgrade runs it
// (StateMigrate, ConfigSyncExisting, UpgradeStoreFlip). The rollback half
// ('tacctl store rollback') is internal/cli's store_rollback_test.go. The
// gate needs the daemon binary for its load-smoke, so tests that expect a
// flip install a stand-in for it. A stop must leave tacquito.yaml byte for
