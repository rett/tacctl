// assertStopped: the install is in legacy read-only mode and the daemon was
// left alone; before is the sha256 tacquito.yaml had before the gate ran.
func (e *tenv) assertStopped(r lifecycle.FlipResult, before string) {
	e.t.Helper()
	out := e.output()
	if r != lifecycle.FlipStopped || r.Code() != 20 || r.String() != "stopped" {
		e.t.Fatalf("result %v\n%s", r, out)
	}
	has(e.t, out, "Store migration stopped")
	has(e.t, out, "legacy read-only mode")
	if sha(e.t, e.p.Config) != before {
		e.t.Error("tacquito.yaml changed")
	}
	if exists(e.p.StoreFile) || exists(e.p.Rendered) {
		e.t.Error("a store or render record was left")
	}
	if len(e.preStoreFiles()) != 0 {
		e.t.Error("a pre-store copy was left")
	}
	if e.systemctlCalled() {
		e.t.Error("systemctl was called")
	}
}

// --- the gate passes ---

func TestFlipALegacyInstallMovesIntoTheStore(t *testing.T) {
	e := newTenv(t)
	e.fakeTacquito("serve")
	e.write(e.p.Config, fixture(t, "legacy.fresh-install.yaml"), 0o640)
	e.upgradeSync()
	before := sha(t, e.p.Config)
	r := e.flip()
	out := e.output()
	if r != lifecycle.Flipped || r.Code() != 0 || r.String() != "flipped" {
		t.Fatalf("result %v\n%s", r, out)
	}
	for _, s := range []string{"[INFO] Store migration: " + e.p.StoreFile + " does not exist yet.",
		"    EQUIVALENT", "daemon load-smoke:   OK", "[INFO] Gate passed: writing the store and rendering " + e.p.Config + " from it...",
		"Store migration complete", "tacctl store rollback"} {
		has(t, out, s)
	}
	// The import's own lines are not repeated by the second, quiet import.
	if strings.Count(out, "Store written to") != 0 {
		t.Error("the import after the check was not quiet")
	}
	if mode(t, e.p.StoreFile) != 0o600 || mode(t, e.p.Config) != 0o640 {
		t.Error("modes")
	}
	if !strings.Contains(strings.SplitN(e.read(e.p.Config), "\n", 2)[0], "GENERATED by tacctl") {
		t.Error("not rendered")
	}
	if w, _ := rendered.Check(e.p.Rendered, e.p.Config); w != rendered.OK {
		t.Errorf("rendered check %q", w)
	}
	// Exactly one copy of the pre-flip file, byte-identical, 0600, named as
	// the plan says, and no second 'drift' copy from the forced render.
	pre := e.preStoreFiles()
	if len(pre) != 1 || !regexp.MustCompile(`/tacquito\.yaml\.pre-store\.[0-9]{8}_[0-9]{6}$`).MatchString(pre[0]) {
		t.Fatalf("pre-store copies %v", pre)
	}
	if sha(t, pre[0]) != before || mode(t, pre[0]) != 0o600 || len(e.legacyFiles()) != 1 {
		t.Error("pre-store copy")
	}
	// What the daemon is given is equivalent to what it had.
	var b bytes.Buffer
	if eq, err := model.EquivCheck(pre[0], e.p.Config, &b); err != nil || !eq || strings.TrimSpace(b.String()) != "EQUIVALENT" {
		t.Errorf("%v %v %q", eq, err, b.String())
	}
	// The gate does not restart; the upgrade does, once, after it.
	if e.systemctlCalled() {
		t.Error("systemctl was called")
	}
}

