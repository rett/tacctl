func TestFlipAnInterruptedUpgradeIsFinishedByTheNextOne(t *testing.T) {
	e := newTenv(t)
	e.fakeTacquito("serve")
	e.write(e.p.Config, fixture(t, "legacy.fresh-install.yaml"), 0o640)
	e.upgradeSync()
	before := sha(t, e.p.Config)
	// The state such an interruption leaves (also what a manual 'tacctl
	// store import' leaves): store written, legacy file still live.
	e.storeImport()
	if !exists(e.p.StoreFile) || exists(e.p.Rendered) || sha(t, e.p.Config) != before {
		t.Fatal("setup")
	}
	e.reset()
	changed, err := lifecycle.ConfigSyncExisting(ctx, e.env, lifecycle.SyncOptions{})
	if err != nil || !changed {
		t.Fatal(changed, err)
	}
	has(t, e.output(), "[INFO] "+e.p.Config+" is equivalent to what the store renders; replacing it with the rendered file.")
	hasNot(t, e.output(), "ERROR")
	// The first sync that renders asks for a restart; the next does not.
	if changed, _ := lifecycle.ConfigSyncExisting(ctx, e.env, lifecycle.SyncOptions{}); changed {
		t.Error("second sync changed")
	}
	if w, _ := rendered.Check(e.p.Rendered, e.p.Config); w != rendered.OK {
		t.Error(w)
	}
	if !strings.Contains(strings.SplitN(e.read(e.p.Config), "\n", 2)[0], "GENERATED by tacctl") {
		t.Error("not rendered")
	}
	// The interrupted run's pre-store copy is the only copy.
	if pre := e.preStoreFiles(); len(pre) != 1 || sha(t, pre[0]) != before || len(e.legacyFiles()) != 1 {
		t.Error(e.legacyFiles())
	}
	if r := e.flip(); r != lifecycle.StorePresent {
		t.Fatal(r)
	}
}

