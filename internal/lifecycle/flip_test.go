func TestFlipStopsOnContentTheStoreCannotRepresent(t *testing.T) {
	e := newTenv(t)
	e.fakeTacquito("serve")
	e.placeFixture("legacy.unrepresentable.yaml")
	e.upgradeSync()
	before := sha(t, e.p.Config)
	e.assertStopped(e.flip(), before)
	out := e.output()
	has(t, out, "Cannot be represented in the store")
	has(t, out, "the check above did not pass")
	has(t, out, "tacctl store import --check")
	hasNot(t, out, "Dropped (--force)")
	// The whole report, as 0.1.16 words it.
	has(t, out, "\n[WARN] Store migration stopped: the check above did not pass.\n"+
		"[WARN] "+e.p.Config+" and the running daemon were left as they are.\n"+
		"[WARN] tacctl stays in legacy read-only mode: read commands work; commands that change users, groups, scopes or filters are refused.\n"+
		"[WARN] To proceed: 'tacctl store import --check' prints the report again. Fix what it lists in "+e.p.Config+" and run 'tacctl upgrade' again,\n"+
		"[WARN] or accept the difference yourself: 'tacctl store import' (--force drops what the store cannot hold), then 'tacctl config render --force'.\n\n")
	// Reads still work from the legacy file.
	_, m, mode, err := model.Load(model.Paths{Store: e.p.StoreFile, Config: e.p.Config})
	if err != nil || mode != "legacy" {
		t.Fatal(mode, err)
	}
	found := false
	for _, u := range m.Users {
		found = found || u.Name == "mallory"
	}
	if !found {
		t.Error("mallory not read")
	}
}

