const secret = "0123456789abcdef0123456789abcdef"

// newSeedEnv is install_seed.bats' setup: a fresh machine (no state
// directory, an empty config directory), the random source answering
// $SECRET as 'openssl rand -hex 16' did.
func newSeedEnv(t *testing.T) *tenv {
	t.Helper()
	e := newTenv(t)
	if err := os.RemoveAll(e.p.StateDir); err != nil {
		t.Fatal(err)
	}
	raw, _ := hex.DecodeString(secret)
	e.env.Rand = bytes.NewReader(raw)
	return e
}

// freshInstall is what cmd_install runs, in its order, up to the point
// the service starts: StateMigrate, then InstallSeed.
func (e *tenv) freshInstall() (lifecycle.SeedResult, error) {
	e.t.Helper()
	if err := lifecycle.StateMigrate(lifecycle.StateOptionsFrom(e.p, e.be.Out, nil, false)); err != nil {
		e.t.Fatal(err)
	}
	e.be.Conf.Reload()
	return lifecycle.InstallSeed(ctx, e.env)
}

func (e *tenv) mustFreshInstall() lifecycle.SeedResult {
	e.t.Helper()
	r, err := e.freshInstall()
	if err != nil {
		e.t.Fatalf("install: %v\n%s", err, e.output())
	}
	return r
}

func TestSeedAFreshInstallSeedsTheStoreAndRendersTacquitoYAML(t *testing.T) {
	e := newSeedEnv(t)
	r := e.mustFreshInstall()
	out := e.output()
	has(t, out, "[INFO] Seeding the store at "+e.p.StoreFile+"...\n")
	has(t, out, "[INFO] Default scope seeded: lab (new users land here unless --scopes given)\n")
	has(t, out, "[INFO] Writing configuration to "+e.p.Config+", "+filepath.Join(e.p.OverrideDir, "tacctl.conf")+"...\n")
	has(t, out, "[INFO] Built-in users seeded (disabled — set a password to activate):\n"+
		"[INFO]   engineer (superuser) — disabled\n"+
		"[INFO]   operator (operator)  — disabled\n"+
		"[INFO]   viewer   (readonly)  — disabled\n"+
		"[INFO]   root     (readonly)  — disabled (accounting sink for Junos internal daemons)\n")
	// The secret is shown once, by the summary, not by the progress lines.
	hasNot(t, out, secret)
	// ...and is handed to the caller with the mode.
	if r.Mode != lifecycle.SeedFresh || r.Secret != secret {
		t.Errorf("%+v", r)
	}
	for p, m := range map[string]os.FileMode{e.p.StateDir: 0o700, e.p.StoreFile: 0o600, e.p.Config: 0o640,
		e.p.Rendered: 0o600, e.p.BackupDir: 0o750, e.p.PWDatesDir: 0o750, filepath.Join(e.p.BackupDir, "disabled"): 0o700} {
		if got := mode(t, p); got != m {
			t.Errorf("%s: %v, want %v", p, got, m)
		}
	}
	if !strings.Contains(strings.SplitN(e.read(e.p.Config), "\n", 2)[0], "GENERATED by tacctl") {
		t.Error("not rendered")
	}
	// Nothing to adopt and nothing displaced on a fresh machine.
	if exists(filepath.Join(e.p.BackupDir, "legacy")) || exists(e.p.Overrides) {
		t.Error("legacy dir or tacctl.yaml made")
	}
	if e.systemctlCalled() {
		t.Error("systemctl")
	}
}

func TestSeedTheStoreHoldsTheBuiltinsTheSeedUsersAndScopeLab(t *testing.T) {
	e := newSeedEnv(t)
	e.mustFreshInstall()
	_, m, err := model.LoadStore(e.p.StoreFile)
	if err != nil {
		t.Fatal(err)
	}
	groups := map[string]string{}
	for _, g := range m.Groups {
		groups[g.Name] = g.JuniperClass
		if !g.Builtin || g.PrivLvl == nil {
			t.Errorf("group %+v", g)
		}
	}
	if len(groups) != 3 || groups["readonly"] != "RO-CLASS" || groups["operator"] != "OP-CLASS" || groups["superuser"] != "RW-CLASS" {
		t.Error(groups)
	}
	want := map[string]string{"engineer": "superuser", "operator": "operator", "viewer": "readonly", "root": "readonly"}
	if len(m.Users) != len(want) {
		t.Error(len(m.Users))
	}
	for _, u := range m.Users {
		if want[u.Name] != u.Group || strings.Join(u.Scopes, ",") != "lab" || u.Hash != "" || !u.Disabled ||
			u.AccountingSink != (u.Name == "root") {
			t.Errorf("user %+v", u)
		}
	}
	if len(m.Scopes) != 1 || m.Scopes[0].Name != "lab" || m.Scopes[0].Secret != secret ||
		strings.Join(m.Scopes[0].Prefixes, ",") != lifecycle.InstallScopePrefixes {
		t.Errorf("scopes %+v", m.Scopes[0])
	}
	if len(m.Filters.Allow)+len(m.Filters.Deny) != 0 {
		t.Error(m.Filters)
	}
	if v, _ := e.be.Conf.Get("scope.default", ""); v != lifecycle.DefaultScopeFresh {
		t.Error(v)
	}
}

// section is sed -n '/^# --- <name> ---/,/^# --- /p'.
func section(text, name string) string {
	re := regexp.MustCompile(`(?ms)^# --- ` + regexp.QuoteMeta(name) + ` ---\n.*?^# --- [^\n]*\n`)
	return re.FindString(text)
}

