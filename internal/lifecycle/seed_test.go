func TestSeedTheSeededStoreIsWhatImportingTheOldFileGives(t *testing.T) {
	e := newSeedEnv(t)
	e.mustFreshInstall()
	seeded, rendered := e.read(e.p.StoreFile), e.read(e.p.Config)
	_ = os.Remove(e.p.StoreFile)
	_ = os.Remove(e.p.Rendered)
	e.write(e.p.Config, fixture(t, "legacy.fresh-install.yaml"), 0o640)
	// The old file passes the upgrade gate as it stands, imports to the same
	// store, and renders to the same file.
	e.fakeTacquito("serve")
	if r := e.flip(); r != lifecycle.Flipped {
		t.Fatalf("%v\n%s", r, e.output())
	}
	has(t, e.output(), "    EQUIVALENT")
	if e.read(e.p.StoreFile) != seeded || e.read(e.p.Config) != rendered {
		t.Error("not the same store or render")
	}
}

func TestSeedAFreshInstallIsFullyWorking(t *testing.T) {
	e := newSeedEnv(t)
	e.mustFreshInstall()
	if lines := e.set.DriftLines(backend.DriftSelection{}); len(lines) != 0 {
		t.Error(lines)
	}
	if w, err := e.b.RenderCheck(ctx); err != nil || w != "current" {
		t.Errorf("render check %q %v", w, err)
	}
	// First mutation: nothing to adopt, nothing refused, the daemon restarts.
	e.reset()
	e.userAdd("alice")
	hasNot(t, e.output(), "Previous")
	if !e.run.Called("systemctl", "restart", "tacquito") {
		t.Error("no restart")
	}
	if w, _ := e.b.RenderCheck(ctx); w != "current" {
		t.Error(w)
	}
}

func TestSeedTheSecretIsTheOneTheRenderedConfigCarries(t *testing.T) {
	e := newSeedEnv(t)
	e.mustFreshInstall()
	cfg := e.read(e.p.Config)
	keys := regexp.MustCompile(`(?m)^      key: "([^"]*)"$`).FindAllStringSubmatch(cfg, -1)
	if len(keys) != 3 {
		t.Fatal(keys)
	}
	for _, k := range keys {
		if k[1] != secret {
			t.Error(k[1])
		}
	}
	for _, p := range strings.Split(lifecycle.InstallScopePrefixes, ",") {
		has(t, cfg, `"`+p+`"`)
	}
}

type failReader struct{}

func (failReader) Read([]byte) (int, error) { return 0, errors.New("no entropy") }

func TestSeedASecretThatCannotBeGeneratedStopsBeforeAnythingIsWritten(t *testing.T) {
	e := newSeedEnv(t)
	e.env.Rand = failReader{}
	if _, err := e.freshInstall(); err == nil {
		t.Fatal("no error")
	}
	has(t, e.output(), "[ERROR] Could not generate a shared secret (openssl rand failed).")
	if exists(e.p.StoreFile) || exists(e.p.Config) {
		t.Error("written")
	}
}

func TestSeedAnExistingStoreIsKept(t *testing.T) {
	e := newSeedEnv(t)
	e.mustFreshInstall()
	e.userAdd("alice")
	storeBefore, configBefore := sha(t, e.p.StoreFile), sha(t, e.p.Config)
	e.reset()
	e.wired.phases = nil
	r := e.mustFreshInstall()
	has(t, e.output(), "[INFO] Existing store found at "+e.p.StoreFile+": its users, groups and scopes are kept (no new shared secret).")
	if r.Mode != lifecycle.SeedStore || r.Secret != "" {
		t.Errorf("%+v", r)
	}
	if sha(t, e.p.StoreFile) != storeBefore || sha(t, e.p.Config) != configBefore {
		t.Error("changed")
	}
	// The enabled backends' 'upgrade config' phase ran (and found nothing to do).
	if len(e.wired.phases) != 1 || e.wired.phases[0] != backend.PhaseConfig || e.wired.synced {
		t.Error(e.wired.phases, e.wired.synced)
	}
}

func TestSeedAnExistingStoreWhoseRenderedConfigIsGoneGetsItBack(t *testing.T) {
	e := newSeedEnv(t)
	e.mustFreshInstall()
	before := sha(t, e.p.Config)
	_ = os.Remove(e.p.Config)
	if r := e.mustFreshInstall(); r.Mode != lifecycle.SeedStore {
		t.Error(r)
	}
	if sha(t, e.p.Config) != before || !e.wired.synced {
		t.Error("not rendered again")
	}
}

func TestSeedAnExistingLegacyConfigGoesThroughTheUpgradeGate(t *testing.T) {
	e := newSeedEnv(t)
	e.fakeTacquito("serve")
	e.write(e.p.Config, fixture(t, filepath.Join("golden", "tacquito.multiscope.rendered.yaml")), 0o640)
	r := e.mustFreshInstall()
	has(t, e.output(), "[INFO] Existing "+e.p.Config+" found: it is kept, not replaced by a fresh configuration.")
	has(t, e.output(), "Store migration complete")
	if r.Mode != lifecycle.SeedFlipped || r.Secret != "" {
		t.Errorf("%+v", r)
	}
	// The users of the existing install, not the seed users.
	_, m, err := model.LoadStore(e.p.StoreFile)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, u := range m.Users {
		names = append(names, u.Name)
	}
	if j := strings.Join(names, " "); !strings.Contains(j, "alice") || strings.Contains(j, "engineer") {
		t.Error(j)
	}
}

func TestSeedAnExistingLegacyConfigTheGateStopsOnIsLeftAsItIs(t *testing.T) {
	e := newSeedEnv(t)
	e.fakeTacquito("serve")
	e.placeFixture("legacy.unrepresentable.yaml")
	r := e.mustFreshInstall()
	if r.Mode != lifecycle.SeedLegacy || r.Secret != "" || exists(e.p.StoreFile) {
		t.Errorf("%+v", r)
	}
	// Byte-identical to the file after the legacy migrations alone.
	after := sha(t, e.p.Config)
	if _, err := lifecycle.ConfigSyncExisting(ctx, e.env, lifecycle.SyncOptions{}); err != nil {
		t.Fatal(err)
	}
	if sha(t, e.p.Config) != after || !strings.Contains(e.read(e.p.Config), "custom_setting") {
		t.Error("changed")
	}
}

func TestSeedARenderThatFailsStopsTheInstall(t *testing.T) {
	e := newSeedEnv(t)
	// A tacctl.yaml adopted from elsewhere enables a backend this tacctl
	// does not have: the store is seeded, the render refuses.
	e.write(e.p.Overrides, "backends:\n  enabled: [ldap]\n", 0o640)
	if _, err := e.freshInstall(); err == nil {
		t.Fatal("no error")
	}
	has(t, e.output(), "tacctl.yaml: backends.enabled names 'ldap'")
	has(t, e.output(), "[ERROR] Could not render  from the store.")
	if !exists(e.p.StoreFile) || exists(e.p.Config) {
		t.Error("files")
	}
}
