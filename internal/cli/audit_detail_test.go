// The host sync line, the enroll line and the unenroll line on success and on
// the failure path (D253, D254).
func TestDetailLinesOfTheHostVerbs(t *testing.T) {
	hs := newHostSandbox(t)
	r := hs.runner()
	hs.run(r, "host", "enroll", "admin@web1.example.net", "--scope", "lab", "--allow-uid-mismatch", "--build-on-host")
	hs.expect(0, "Host 'web1' enrolled.", "")
	if !hasAudit(r, "auth.info", "host enroll name=web1 target=admin@web1.example.net scope=lab method=tacplus by=root result=ok") {
		t.Errorf("enroll: %q", auditLines(r))
	}
	r = hs.runner()
	hs.run(r, "host", "sync", "web1")
	hs.expect(0, "web1: synced", "")
	if !hasAudit(r, "auth.info", "host sync name=web1 target=admin@web1.example.net created=0 updated=0 renamed=0 removed=0 remove-home=no result=ok by=root") {
		t.Errorf("sync: %q", auditLines(r))
	}
	hs.runFails = true
	r = hs.runner()
	hs.run(r, "host", "sync", "web1", "--remove-home")
	hs.expect(1, "", "web1: sync failed")
	if !hasAudit(r, "auth.warning", "host sync name=web1 target=admin@web1.example.net created=0 updated=0 renamed=0 removed=0 remove-home=yes result=failed reason=script by=root") {
		t.Errorf("failed sync: %q", auditLines(r))
	}
	// An enrolment whose script fails on the host is a failed line (D254).
	r = hs.runner()
	hs.run(r, "host", "enroll", "admin@web1.example.net", "--scope", "lab", "--build-on-host")
	hs.expect(1, "", "Enrollment of web1 failed")
	if !hasAudit(r, "auth.warning", "host enroll name=web1 target=admin@web1.example.net scope=lab method=tacplus by=root result=failed reason=script") {
		t.Errorf("failed enroll: %q", auditLines(r))
	}
	r = hs.runner()
	hs.run(r, "host", "unenroll", "web1")
	hs.expect(1, "", "Removal on web1 failed")
	if !hasAudit(r, "auth.warning", "host unenroll name=web1 target=admin@web1.example.net by=root force=no result=failed reason=script") {
		t.Errorf("failed unenroll: %q", auditLines(r))
	}
	r = hs.runner()
	hs.run(r, "host", "unenroll", "web1", "--force")
	hs.expect(0, "forgetting the host anyway", "")
	if !hasAudit(r, "auth.info", "host unenroll name=web1 target=admin@web1.example.net by=root force=yes result=ok") {
		t.Errorf("forced unenroll: %q", auditLines(r))
	}
}

// The reason of a failed run is the class of its text, never the text.
func TestFailedRunReasonWords(t *testing.T) {
	for in, want := range map[string]string{
		"the client script failed on the host (exit status 3)": "script", "interrupted": "interrupted",
		"its scope 'x' no longer exists":                 "scope",
		"the host cannot hold the UID range 80000-89999": "uid-range", "the client script could not be written": "script-write",
		"something else": "error",
	} {
		if got := runReasonWord(in); got != want {
			t.Errorf("%q: %s, want %s", in, got, want)
		}
	}
	if failReason(ui.ErrInterrupted, "store") != "interrupted" || failReason(errors.New("x"), "store") != "store" {
		t.Error("failReason")
	}
}

