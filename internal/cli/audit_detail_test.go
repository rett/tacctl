// A change that failed has no detail line and its end line says failed; a
// command that changed nothing has no pair and no detail line.
func TestNoDetailLineWithoutAChange(t *testing.T) {
	sb := newSandbox(t, true)
	sb.asAlice("", "user", "move", "bob", "nosuchgroup")
	if sb.code != 1 || hasAuditPrefix(sb.runner, "", "user move") {
		t.Errorf("exit %d, lines %q", sb.code, auditLines(sb.runner))
	}
	sb.asAlice("", "user", "move", "bob", "operator")
	if hasAuditPrefix(sb.runner, "", "user move") || len(centralLines(sb.runner)) != 2 {
		t.Errorf("an unchanged group wrote %q", auditLines(sb.runner))
	}
	sb.asAlice("", "scope", "protocols", "lab", "clear")
	if hasAuditPrefix(sb.runner, "", "scope protocols") {
		t.Errorf("a clear of nothing wrote %q", auditLines(sb.runner))
	}
	sb.asAlice("", "scope", "snmp", "lab", "show")
	if hasAuditPrefix(sb.runner, "", "snmp set") {
		t.Errorf("a show wrote %q", auditLines(sb.runner))
	}
}

// A secret shown is a secret-read line for every caller, the superuser's
// too (D253); the reads have no pair, the verbs are reads.
func TestSecretReadIsLoggedForEveryCaller(t *testing.T) {
	sb := newSandbox(t, true)
	for _, c := range []struct {
		name string
		args []string
		line string
	}{
		{"scope secret show", []string{"scope", "secret", "lab", "show"}, "secret-read kind=scope name=lab by=alice"},
		{"scope snmp reveal", []string{"scope", "snmp", "lab", "show", "--reveal"}, "secret-read kind=snmp name=lab by=alice"},
		{"config snmp reveal", []string{"config", "snmp", "show", "--reveal"}, "secret-read kind=snmp-default name=default by=alice"},
		{"store show", []string{"store", "show"}, "secret-read kind=store name=model by=alice"},
		{"config dump", []string{"config", "dump"}, "secret-read kind=config name=dump by=alice"},
	} {
		sb.asAlice("", c.args...)
		if sb.code != 0 {
			t.Errorf("%s: exit %d %q", c.name, sb.code, sb.stderr())
			continue
		}
		if !hasAudit(sb.runner, "auth.info", c.line) || len(centralLines(sb.runner)) != 0 {
			t.Errorf("%s: lines %q, want %s alone", c.name, auditLines(sb.runner), c.line)
		}
	}
	// A device's own credentials.
	sb.dev("", "add", "lab-sw", "192.168.1.1", "--vendor", "cisco", "--no-host-key", "--no-lookup")
	sb.asAlice("Device-community-1a2b3c\n", "device", "snmp", "lab-sw", "community", "--stdin")
	sb.asAlice("", "device", "snmp", "lab-sw", "show", "--reveal")
	if sb.code != 0 || !hasAuditPrefix(sb.runner, "auth.info", "secret-read kind=snmp") {
		t.Errorf("device snmp reveal: exit %d %q", sb.code, auditLines(sb.runner))
	}
	// A snapshot's diff.
	sb.asAlice("", "user", "disable", "bob")
	id := sb.snapshotID()
	sb.asAlice("", "backup", "diff", id)
	if !hasAudit(sb.runner, "auth.info", "secret-read kind=snapshot name="+id+" by=alice") {
		t.Errorf("backup diff: %q", auditLines(sb.runner))
	}
}

// snapshotID is the newest snapshot of the sandbox.
func (sb *sandbox) snapshotID() string {
	sb.t.Helper()
	sb.asAlice("", "backup", "list")
	m := regexp.MustCompile(`\d{8}_\d{6}_\d{3}`).FindString(plain(sb.out.String()))
	if m == "" {
		sb.t.Fatalf("no snapshot in %q", sb.out.String())
	}
	return m
}

