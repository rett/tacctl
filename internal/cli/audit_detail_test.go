// The detail lines (docs/plans/0.2.17-plan.md D253, D254): a verb that
// changes something writes a line of its own between the cmd start and the
// cmd end of its pair, with the object, the value before and after, and the
// actor last.

// detailIndex is the position of the exact line at priority among the run's
// audit calls, -1 when it is not there.
func detailIndex(calls []auditCall, priority, line string) int {
	for i, c := range calls {
		if c.Tag == "tacctl" && c.Priority == priority && c.Line == line {
			return i
		}
	}
	return -1
}

// wantDetail fails unless the run wrote line at priority between the start
// and the end line of its pair.
func wantDetail(t *testing.T, name string, calls []auditCall, priority, line string) {
	t.Helper()
	i := detailIndex(calls, priority, line)
	if i < 0 {
		var all []string
		for _, c := range calls {
			all = append(all, c.Priority+" "+c.Line)
		}
		t.Errorf("%s: no %s line %q in %q", name, priority, line, all)
		return
	}
	start, end := -1, -1
	for j, c := range calls {
		switch {
		case strings.HasPrefix(c.Line, "cmd start "):
			start = j
		case strings.HasPrefix(c.Line, "cmd end "):
			end = j
		}
	}
	if start < 0 || end < 0 || i <= start || i >= end {
		t.Errorf("%s: the line %q is at %d, the pair at %d and %d", name, line, i, start, end)
	}
}

