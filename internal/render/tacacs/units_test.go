func TestStageUnitsIndexAndReadIndex(t *testing.T) {
	w := t.TempDir()
	p := Paths{OverrideDir: filepath.Join(w, "sd", "tacquito.service.d"), UnitDir: filepath.Join(w, "sd"),
		LogDir: "/l", Rendered: filepath.Join(w, "rendered.json")}
	view := viewOf(t, "listeners:\n  tacacs:\n    mgmt: {network: tcp, address: '127.0.0.1:4949'}\n").Merged()
	units, err := Units(view, "/l")
	if err != nil {
		t.Fatal(err)
	}
	// The default drop-in is live and as rendered, mgmt's is not there.
	writeFile(t, DropIn(p, "default"), units[0].Text)
	out := filepath.Join(w, "stage", "units")
	idx, err := StageUnits(view, out, p)
	if err != nil {
		t.Fatal(err)
	}
	want := "default\tsame\t" + DropIn(p, "default") + "\nmgmt\tmissing\t" + DropIn(p, "mgmt") + "\n"
	if got := string(readFile(t, filepath.Join(out, IndexName))); got != want {
		t.Fatalf("index\n%q\nwant\n%q", got, want)
	}
	back, err := ReadIndex(out)
	if err != nil || len(back) != 2 || back[0] != idx[0] || back[1] != idx[1] || back[1].Status != rendered.Missing {
		t.Fatalf("%v %v %v", back, idx, err)
	}
	if string(readFile(t, filepath.Join(out, "mgmt.conf"))) != units[1].Text {
		t.Fatal("mgmt.conf")
	}
	// Recorded: current.
	if err := rendered.Record(p.Rendered, DropIn(p, "default")); err != nil {
		t.Fatal(err)
	}
	idx, _ = StageUnits(view, out, p)
	if idx[0].Status != rendered.Current {
		t.Fatalf("%v", idx)
	}
	// No index: no units.
	if l, err := ReadIndex(filepath.Join(w, "nothing")); l != nil || err != nil {
		t.Fatalf("%v %v", l, err)
	}
	// A listener model that cannot be served stages nothing.
	if _, err := StageUnits(viewOf(t, "backends:\n  tacacs:\n    level: x\n").Merged(), filepath.Join(w, "s2"), p); err == nil {
		t.Fatal("staged")
	}
	if _, err := os.Stat(filepath.Join(w, "s2")); err == nil {
		t.Fatal("the stage dir was created")
	}
}
