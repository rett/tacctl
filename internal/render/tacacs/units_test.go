func productionPaths() Paths {
	return PathsFrom(paths.Resolve(paths.NewEnv(nil), "", func(string) bool { return false }))
}

func unitsOf(t *testing.T, tacctlYAML, logDir string) map[string]string {
	t.Helper()
	units, err := Units(viewOf(t, tacctlYAML).Merged(), logDir)
	if err != nil {
		t.Fatal(rendered.Report(err))
	}
	out := map[string]string{}
	for _, u := range units {
		out[u.Listener] = u.Text
	}
	return out
}

// The drop-ins with the production log directory, against 0.1.16's
// output (testdata/gen.py wrote the goldens from its corpus).
func TestDropInGoldens(t *testing.T) {
	logDir := productionPaths().LogDir
	def := unitsOf(t, "", logDir)
	if len(def) != 1 {
		t.Fatalf("listeners %v", def)
	}
	diffText(t, []byte(def["default"]), readFile(t, filepath.Join(goldenDir, "dropin.default.conf")), "dropin.default.conf")

	units, err := Units(viewOf(t, "backends:\n  tacacs:\n    level: 30\nlisteners:\n  tacacs:\n"+
		"    default:\n      network: tcp\n      address: 10.1.0.1:49\n"+
		"    mgmt:\n      network: tcp\n      address: 127.0.0.1:4949\n"+
		"    alt6:\n      network: tcp6\n      address: '[::1]:4950'\n      metrics_address: '[::1]:9100'\n").Merged(), logDir)
	if err != nil {
		t.Fatal(err)
	}
	var order []string
	for _, u := range units {
		order = append(order, u.Listener)
		golden := map[string]string{"default": "dropin.default-override.conf", "mgmt": "dropin.mgmt.conf", "alt6": "dropin.alt6.conf"}[u.Listener]
		diffText(t, []byte(u.Text), readFile(t, filepath.Join(goldenDir, golden)), golden)
	}
	// The default listener first, then the others by name.
	if strings.Join(order, " ") != "default alt6 mgmt" {
		t.Fatalf("order %v", order)
	}
}

// listeners.bats "drop-in: one settings change renders every flag of the
// default listener", at the renderer.
func TestDropInRendersEveryFlagOfTheDefaultListener(t *testing.T) {
	d := unitsOf(t, "listeners:\n  tacacs:\n    default: {network: tcp, address: '10.1.0.1:49'}\n", "/tmp/log")["default"]
	lines := strings.Split(d, "\n")
	if !strings.Contains(lines[0], "GENERATED by tacctl from tacctl.yaml") {
		t.Fatalf("first line %q", lines[0])
	}
	for _, want := range []string{"[Service]", `Environment="TACQUITO_NETWORK=tcp"`, `Environment="TACQUITO_ADDRESS=10.1.0.1:49"`,
		`Environment="TACQUITO_LEVEL=20"`, `Environment="TACQUITO_METRICS_ADDRESS=127.0.0.1:8080"`,
		`Environment="TACQUITO_ACCT_LOG=/tmp/log/accounting.log"`} {
		if !containsLine(lines, want) {
			t.Fatalf("no line %q in\n%s", want, d)
		}
	}
}

func containsLine(lines []string, want string) bool {
	for _, l := range lines {
		if l == want {
			return true
		}
	}
	return false
}

// "drop-in: an instance gets its own address, accounting log and no
// reachable metrics".
func TestDropInOfAnInstance(t *testing.T) {
	u := unitsOf(t, "backends:\n  tacacs:\n    level: 30\nlisteners:\n  tacacs:\n    mgmt: {network: tcp, address: '127.0.0.1:4949'}\n", "/l")
	mgmt := strings.Split(u["mgmt"], "\n")
	for _, want := range []string{`Environment="TACQUITO_NETWORK=tcp"`, `Environment="TACQUITO_ADDRESS=127.0.0.1:4949"`,
		`Environment="TACQUITO_LEVEL=30"`, `Environment="TACQUITO_METRICS_ADDRESS=127.0.0.1:0"`,
		`Environment="TACQUITO_ACCT_LOG=/l/accounting-mgmt.log"`} {
		if !containsLine(mgmt, want) {
			t.Fatalf("no line %q in\n%s", want, u["mgmt"])
		}
	}
	def := strings.Split(u["default"], "\n")
	if !containsLine(def, `Environment="TACQUITO_ADDRESS=:49"`) || !containsLine(def, `Environment="TACQUITO_ACCT_LOG=/l/accounting.log"`) {
		t.Fatalf("default:\n%s", u["default"])
	}
}

// "drop-in: a listener's own metrics_address is rendered; the default
// listener's is refused for it".
func TestDropInMetricsAddressOfAnInstance(t *testing.T) {
	u := unitsOf(t, "listeners:\n  tacacs:\n    mgmt: {network: tcp, address: '127.0.0.1:4949', metrics_address: '127.0.0.1:9100'}\n", "/l")
	if !containsLine(strings.Split(u["mgmt"], "\n"), `Environment="TACQUITO_METRICS_ADDRESS=127.0.0.1:9100"`) {
		t.Fatalf("mgmt:\n%s", u["mgmt"])
	}
	_, err := Units(viewOf(t, "listeners:\n  tacacs:\n    mgmt: {network: tcp, address: '127.0.0.1:4949', metrics_address: '127.0.0.1:8080'}\n").Merged(), "/l")
	if err == nil || !strings.Contains(err.Error(), "metrics_address 127.0.0.1:8080 is the default listener's") {
		t.Fatalf("got %v", err)
	}
	// The sink may be shared: it is not reachable.
	if _, err := Units(viewOf(t, "backends:\n  tacacs:\n    metrics_address: 127.0.0.1:0\nlisteners:\n  tacacs:\n    mgmt: {network: tcp, address: '127.0.0.1:4949'}\n").Merged(), "/l"); err != nil {
		t.Fatal(err)
	}
}

// "render: a listener model that cannot be served fails the render".
func TestDropInRefusals(t *testing.T) {
	for text, want := range map[string]string{
		"listeners:\n  tacacs:\n    tls: {network: tcp, address: ':300', tls: {enabled: true}}\n": "tacctl.yaml: listeners.tacacs.tls: tls.enabled: true is reserved for a future release (TLS listeners are not implemented)",
		"backends:\n  tacacs: [1]\n":                        "tacctl.yaml: backends.tacacs is not a mapping",
		"backends:\n  tacacs:\n    level: debug\n":          "tacctl.yaml: backends.tacacs.level is not a log level (10, 20 or 30)",
		"backends:\n  tacacs:\n    level: -1\n":             "tacctl.yaml: backends.tacacs.level is not a log level (10, 20 or 30)",
		"backends:\n  tacacs:\n    metrics_address: 80\n":   "tacctl.yaml: backends.tacacs.metrics_address must be a string host:port",
		"backends:\n  tacacs:\n    metrics_address: ':x'\n": "tacctl.yaml: backends.tacacs.metrics_address must be host:port (e.g. '127.0.0.1:8080' or ':8080')",
	} {
		_, err := Units(viewOf(t, text).Merged(), "/l")
		if err == nil || err.Error() != want {
			t.Fatalf("%q: got %v", text, err)
		}
	}
}

