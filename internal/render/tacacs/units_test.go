// "units: the paths tacctl derives for a listener" (tests/unit/listeners.bats).
func TestUnitPaths(t *testing.T) {
	p := Paths{OverrideDir: "/o/tacquito.service.d", UnitDir: "/u", LogDir: "/log", AcctLog: "/log/accounting.log"}
	for _, tc := range [][2]string{
		{Unit("default"), "tacquito.service"}, {Unit(""), "tacquito.service"}, {Unit("mgmt"), "tacquito@mgmt.service"},
		{DropIn(p, "default"), "/o/tacquito.service.d/tacctl.conf"}, {DropIn(p, "mgmt"), "/u/tacquito@mgmt.service.d/tacctl.conf"},
		{AcctLog(p, "default"), "/log/accounting.log"}, {AcctLog(p, "mgmt"), "/log/accounting-mgmt.log"},
	} {
		if tc[0] != tc[1] {
			t.Fatalf("got %s, want %s", tc[0], tc[1])
		}
	}
	// Production paths, when nothing is overridden.
	prod := productionPaths()
	got := strings.Join([]string{"/etc/systemd/system/" + UnitName, DropIn(prod, "default"), DropIn(prod, "mgmt"),
		prod.OverrideDir + "/" + LegacyDropInName, prod.AcctLog, AcctLog(prod, "mgmt")}, " ")
	want := "/etc/systemd/system/tacquito.service /etc/systemd/system/tacquito.service.d/tacctl.conf " +
		"/etc/systemd/system/tacquito@mgmt.service.d/tacctl.conf /etc/systemd/system/tacquito.service.d/tacctl-overrides.conf " +
		"/var/log/tacquito/accounting.log /var/log/tacquito/accounting-mgmt.log"
	if got != want || prod.UnitDir != "/etc/systemd/system" {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
	// TACCTL_SYSTEMD_DIR moves the instances, TACCTL_OVERRIDE_DIR the default.
	q := PathsFrom(paths.Resolve(paths.NewEnv([]string{"TACCTL_OVERRIDE_DIR=/x/d"}), "", func(string) bool { return false }))
	if DropIn(q, "mgmt") != "/x/tacquito@mgmt.service.d/tacctl.conf" || DropIn(q, "default") != "/x/d/tacctl.conf" {
		t.Fatalf("%s %s", DropIn(q, "mgmt"), DropIn(q, "default"))
	}
}

// "units: both take every per-listener flag from the environment", and
// the drop-in sets exactly those flags; the defaults the units carry are
// the renderer's ("the shell constants are the python renderer's and the
// unit's defaults", unit half).
func TestUnitsTakeEveryFlagTheDropInSets(t *testing.T) {
	d := unitsOf(t, "", "/l")["default"]
	var vars []string
	for _, m := range regexp.MustCompile(`(?m)^Environment="(TACQUITO_[A-Z_]+)=`).FindAllStringSubmatch(d, -1) {
		vars = append(vars, m[1])
	}
	if strings.Join(vars, " ") != "TACQUITO_NETWORK TACQUITO_ADDRESS TACQUITO_LEVEL TACQUITO_METRICS_ADDRESS TACQUITO_ACCT_LOG" {
		t.Fatalf("drop-in sets %v", vars)
	}
	for _, f := range []string{"tacquito.service", "tacquito@.service"} {
		unit := string(readFile(t, filepath.Join(unitsDir, f)))
		for _, v := range vars {
			if !strings.Contains(unit, "${"+v+"}") {
				t.Fatalf("%s does not use ${%s}", f, v)
			}
		}
	}
	unit := strings.Split(string(readFile(t, filepath.Join(unitsDir, "tacquito.service"))), "\n")
	for _, want := range []string{`Environment="TACQUITO_LEVEL=20"`, `Environment="TACQUITO_METRICS_ADDRESS=` + MetricsDefault + `"`,
		`Environment="TACQUITO_NETWORK=tcp"`, `Environment="TACQUITO_ADDRESS=:49"`} {
		if !containsLine(unit, want) {
			t.Fatalf("tacquito.service has no %s", want)
		}
	}
	if LevelDefault != 20 {
		t.Fatal("LevelDefault")
	}
}

