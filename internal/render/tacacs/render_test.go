func TestGroupCommandsShapes(t *testing.T) {
	for text, want := range map[string]string{
		"":                                 "[{* permit []}]",
		"commands: {}\n":                   "[{* permit []}]", // a mapping merges into the defaults
		"commands:\n  superuser: ''\n":     "[]",
		"commands:\n  superuser: {}\n":     "[]",
		"commands:\n  superuser: {a: 1}\n": "tacctl.yaml: commands.superuser is not a list of rules",
		"commands:\n  superuser:\n  - {name: x, match: ''}\n":                   "[{x permit []}]",
		"commands:\n  superuser:\n  - {name: x, match: {}}\n":                   "[{x permit []}]",
		"commands:\n  superuser:\n  - {name: x, match: {a: 1}}\n":               "tacctl.yaml: commands.superuser: rule 'x' has a match that is not a list of strings",
		"commands:\n  superuser:\n  - {name: x, action: [permit]}\n":            "tacctl.yaml: commands.superuser: rule 'x' has an action that is neither permit nor deny",
		"commands:\n  superuser:\n  - {name: x, action: deny, match: [a, b]}\n": "[{x deny [a b]}]",
		"commands:\n  superuser:\n  - [x]\n":                                    "tacctl.yaml: commands.superuser has a rule without a name",
		"commands: ''\n":                                                        "[]",
		"commands: 5\n":                                                         "tacctl.yaml: commands is not a mapping of groups",
	} {
		rules, err := GroupCommands(viewOf(t, text).Merged(), "superuser")
		got := fmt.Sprint(rules)
		if err != nil {
			got = err.Error()
		}
		if rules == nil && err == nil {
			got = "[]"
		}
		if got != want {
			t.Fatalf("%q: got %s, want %s", text, got, want)
		}
	}
}
