// RenderToFile writes nothing when the read-back fails, and says what
// the importer reported.
func TestRenderToFileWritesNothingWhenTheReadbackFails(t *testing.T) {
	dir := t.TempDir()
	out := filepath.Join(dir, "tacquito.yaml")
	lying := func(path string) (*LegacyResult, error) {
		r, err := testLoad(path)
		if err != nil {
			return nil, err
		}
		r.Errors = []string{"users[0]: not a mapping"}
		r.Dropped = []string{"unknown top-level key 'x'"}
		return r, nil
	}
	_, err := RenderToFile(loadStore(t, "store.multiscope.yaml"), defaultView(t), out, lying, nil)
	want := "tacctl render: internal error: the rendered config does not read back as the model (" +
		"importer reports: users[0]: not a mapping; importer reports: unknown top-level key 'x'). Nothing was written."
	if err == nil || rendered.Report(err) != want {
		t.Fatalf("got %v", err)
	}
	if entries, _ := os.ReadDir(dir); len(entries) != 0 {
		t.Fatalf("left behind: %v", entries)
	}
	// A loader that refuses the file outright fails the render with its words.
	refusing := func(string) (*LegacyResult, error) {
		return nil, &store.Error{Msg: "x.yaml: top level is not a YAML mapping"}
	}
	if _, err := RenderToFile(loadStore(t, "store.multiscope.yaml"), defaultView(t), out, refusing, nil); err == nil ||
		rendered.Report(err) != "tacctl render: x.yaml: top level is not a YAML mapping" {
		t.Fatalf("got %v", err)
	}
	// No loader at all is an internal error, never an unchecked file.
	if _, err := RenderToFile(loadStore(t, "store.multiscope.yaml"), defaultView(t), out, nil, nil); err == nil {
		t.Fatal("rendered without a read-back")
	}
	if _, err := os.Stat(out); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("something was written")
	}
}

// Each difference the read-back looks for is named.
func TestReadbackProblemsNamesEachDifference(t *testing.T) {
	st := loadStore(t, "store.multiscope.yaml")
	m := model.FromStore(st)
	p := filepath.Join(t.TempDir(), "t.yaml")
	writeFile(t, p, string(render(t, st, defaultView(t))))
	if probs, err := ReadbackProblems(p, m, testLoad); err != nil || len(probs) != 0 {
		t.Fatalf("%v %v", probs, err)
	}
	for _, tc := range []struct {
		edit func(st *store.Store)
		want string
	}{
		{func(st *store.Store) { entry(st, "groups", "operator").Set("priv_lvl", 6) }, "groups differ"},
		{func(st *store.Store) { entry(st, "groups", "operator").Set("juniper_class", "X") }, "groups differ"},
		{func(st *store.Store) { entry(st, "users", "bob").Set("scopes", []any{"prod"}) }, "users differ"},
		{func(st *store.Store) { entry(st, "users", "bob").Set("disabled", true) }, "users differ"},
		{func(st *store.Store) { entry(st, "scopes", "dmz").Set("prefixes", []any{"203.0.113.0/25"}) }, "scopes differ"},
		{func(st *store.Store) { entry(st, "scopes", "dmz").Set("protocols", []any{"radius"}) }, "users differ; scopes differ"},
		{func(st *store.Store) { section(st, "filters").Set("allow", []any{"10.0.0.0/8"}) }, "filters.allow differs"},
		{func(st *store.Store) { section(st, "filters").Set("deny", []any{"10.0.0.0/8"}) }, "filters.deny differs"},
	} {
		other := loadStore(t, "store.multiscope.yaml")
		tc.edit(other)
		probs, err := ReadbackProblems(p, model.FromStore(other), testLoad)
		if err != nil || strings.Join(probs, "; ") != tc.want {
			t.Fatalf("want %q, got %v %v", tc.want, probs, err)
		}
		if MatchesModel(p, model.FromStore(other), testLoad) {
			t.Fatal("matches")
		}
	}
	if !MatchesModel(p, m, testLoad) {
		t.Fatal("the render does not match its own model")
	}
	// Prefixes and filters compare canonicalised, deduplicated and sorted.
	if got := canonList([]string{"10.1.0.0/16", "10.0.0.0/8", " 10.1.0.0/16", "10.0.0.1/8"}); fmt.Sprint(got) != "[10.1.0.0/16 10.0.0.0/8]" {
		t.Fatalf("canonList %v", got)
	}
	if got := canonList([]string{"10.0.0.0/8", "bogus"}); fmt.Sprint(got) != "[10.0.0.0/8 bogus]" {
		t.Fatalf("canonList %v", got)
	}
	// A file whose command rules differ from tacctl.yaml.
	err := Readback(p, m, viewOf(t, "commands:\n  operator: []\n").Merged(), testLoad)
	if err == nil || !strings.Contains(err.Error(), "(command rules of group 'operator' differ)") {
		t.Fatalf("got %v", err)
	}
}

