func TestRenderCustomGroupsFollowTheBuiltins(t *testing.T) {
	st := loadStore(t, "store.multiscope.yaml")
	section(st, "groups").Set("helpdesk", yamlpy.NewMap("priv_lvl", 5, "juniper_class", "HELPDESK-CLASS", "builtin", false))
	section(st, "groups").Set("auditor", yamlpy.NewMap("priv_lvl", 2, "juniper_class", "AUDIT", "builtin", false))
	entry(st, "users", "bob").Set("group", "helpdesk")
	text := render(t, st, defaultView(t))
	keys := regexp.MustCompile(`(?m)^[a-z_]+: &[a-z]+$`).FindAllString(string(text), -1)
	if strings.Join(keys, "|") != "readonly: &readonly|operator: &operator|superuser: &superuser|auditor: &auditor|helpdesk: &helpdesk" {
		t.Fatalf("group keys %v", keys)
	}
	g := usersOf(decoded(t, text))["bob"]["groups"].([]any)[0].(map[string]any)
	var svc []string
	for _, s := range g["services"].([]any) {
		m := s.(map[string]any)
		sv := m["set_values"].([]any)[0].(map[string]any)
		svc = append(svc, fmt.Sprint(m["name"], " ", sv["name"], " ", sv["values"]))
	}
	if g["name"] != "helpdesk" || strings.Join(svc, ", ") != "shell priv-lvl [5], junos-exec local-user-name [HELPDESK-CLASS]" {
		t.Fatalf("%v %v", g["name"], svc)
	}
	if _, has := g["commands"]; has {
		t.Fatal("helpdesk has command rules")
	}
}

