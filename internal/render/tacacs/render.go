// Header is RENDER_HEADER, the comment block tacquito.yaml starts with.
const Header = "# GENERATED by tacctl from /etc/tacctl/store.yaml and tacctl.yaml. Edits here are overwritten.\n" +
	"# Use tacctl commands, or 'tacctl store import --replace' to adopt manual edits.\n" +
	"#\n" +
	"# Tacquito TACACS+ server configuration (Cisco IOS/IOS-XE + Juniper).\n"

// BuiltinRenderOrder is the order the built-in groups are listed in.
var BuiltinRenderOrder = []string{"readonly", "operator", "superuser"}

// yamlWords are the words PyYAML (YAML 1.1) reads as a boolean or null
// when left unquoted.
var yamlWords = []string{"y", "n", "yes", "no", "on", "off", "true", "false", "null"}

// LegacyTopKeys and LegacyConstants are the importer's (lib/model.sh)
// top-level keys of the layout; with file_accounter they are the keys a
// group may not take (RENDER_TOP_KEYS).
var (
	LegacyTopKeys   = []string{"users", "secrets", "prefix_allow", "prefix_deny"}
	LegacyConstants = []string{"authenticator_type_bcrypt", "action_deny", "action_permit",
		"accounter_type_file", "handler_type_start", "provider_type_prefix"}
	renderKeyPrefixes = []string{"exec_", "junos_exec_", "wti_exec_", "bcrypt_", "group_"}
)

// Actions are the values tacquito gives a command rule's action.
var Actions = map[string]int{"permit": 2, "deny": 1}

// Protocol is the scope 'protocols' entry this backend serves.
const Protocol = "tacacs"

// YQ is yq: a YAML double-quoted scalar that every YAML parser decodes to
// exactly s; the result is ASCII ("\xNN", "\uNNNN", "\UNNNNNNNN" escapes).
func YQ(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r >= 0x20 && r < 0x7f:
			b.WriteRune(r)
		case r <= 0xff:
			fmt.Fprintf(&b, `\x%02x`, r)
		case r <= 0xffff:
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			fmt.Fprintf(&b, `\U%08x`, r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

var reName = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_-]*$`)

// YName is yname: a name as a plain scalar, as tacctl always wrote it,
// unless a parser could read that as something other than the string.
func YName(s string) string {
	if reName.MatchString(s) && !slices.Contains(yamlWords, strings.ToLower(s)) {
		return s
	}
	return YQ(s)
}

// userAnchors are the anchor suffixes of the users' bcrypt authenticators
// (&bcrypt_<suffix>), in the order of users. YAML anchors hold letters,
// digits, '_' and '-' only (tacquito's parser refuses a period), so a name
// is its own suffix unless it has a period: then each period is written
// "_dot_", and a number is added where that equals the suffix of another
// user. A user name without a period keeps the suffix it always had.
func userAnchors(users []*model.User) []string {
	out := make([]string, len(users))
	taken := make(map[string]bool, len(users))
	for i, u := range users {
		if !strings.Contains(u.Name, ".") {
			out[i] = u.Name
			taken[u.Name] = true
		}
	}
	for i, u := range users {
		if !strings.Contains(u.Name, ".") {
			continue
		}
		base := strings.ReplaceAll(u.Name, ".", "_dot_")
		cand := base
		for n := 2; taken[cand]; n++ {
			cand = base + "_" + strconv.Itoa(n)
		}
		taken[cand] = true
		out[i] = cand
	}
	return out
}

// GroupKey is group_key: the top-level key and anchor of a group, its
// name unless that would collide with a key the layout owns.
func GroupKey(name string) string {
	if slices.Contains(LegacyTopKeys, name) || slices.Contains(LegacyConstants, name) || name == "file_accounter" {
		return "group_" + name
	}
	for _, p := range renderKeyPrefixes {
		if strings.HasPrefix(name, p) {
			return "group_" + name
		}
	}
	return name
}

// GroupOrder is group_order: the built-in groups present in their order,
// then the others by name.
func GroupOrder(names []string) []string {
	var first, rest []string
	for _, b := range BuiltinRenderOrder {
		if slices.Contains(names, b) {
			first = append(first, b)
		}
	}
	for _, n := range names {
		if !slices.Contains(first, n) {
			rest = append(rest, n)
		}
	}
	sort.Strings(rest)
	return append(first, rest...)
}

// Rule is one validated command rule of commands.<group>.
type Rule struct {
	Name   string
	Action string // permit | deny
	Match  []string
}

// WrapMatch is what a stored match regex is rendered as: ^(?:regex)$.
// tacquito appends '$' and prepends '^' only when they are missing, so a
// bare top-level alternation ('a|b') would be tested as '^a|b$' (a prefix
// match on one branch, a suffix match on the other). Wrapped, the regex
// must match the whole arguments string and its alternation stays inside.
// An empty regex stays empty (tacquito skips it).
func WrapMatch(rx string) string {
	if rx == "" {
		return rx
	}
	return "^(?:" + rx + ")$"
}

// noWrap switches WrapMatch off for the one test that replays 0.1.16's
// own output byte for byte (corpus_test.go); nothing else sets it.
var noWrap bool

// renderMatch is a stored regex as the file carries it.
func renderMatch(rx string) string {
	if noWrap {
		return rx
	}
	return WrapMatch(rx)
}

// UnwrapMatch is WrapMatch undone, for reading a rendered file back (the
// legacy importer); a regex that is not wrapped is returned as it is. The
// '^(?:' and ')$' of a rendered file are the wrapper only when what stands
// between them is a regex of its own: its parentheses pair up and it
// compiles. A file written before 0.2.3 had tacquito's own anchoring and
// '^(?:a)|(?:b)$' was a regex of the operator's (the alternation 'a|b' in
// two groups); taking its ends for a wrapper would give 'a)|(?:b'.
func UnwrapMatch(rx string) string {
	if strings.HasPrefix(rx, "^(?:") && strings.HasSuffix(rx, ")$") && len(rx) >= len("^(?:)$") {
		inner := rx[len("^(?:") : len(rx)-len(")$")]
		if parensPair(inner) {
			if _, err := regexp.Compile(inner); err == nil {
				return inner
			}
		}
	}
	return rx
}

// parensPair reports whether the groups of a regex open and close in order:
// no ')' without its '(' and none left open, a backslash taking the next
// byte and a character class counting as one.
func parensPair(rx string) bool {
	depth, class := 0, false
	for i := 0; i < len(rx); i++ {
		switch c := rx[i]; {
		case c == '\\':
			i++
		case class:
			if c == ']' {
				class = false
			}
		case c == '[':
			class = true
			// A ']' right after '[' or '[^' is a member of the class.
			if i+1 < len(rx) && rx[i+1] == '^' {
				i++
			}
			if i+1 < len(rx) && rx[i+1] == ']' {
				i++
			}
		case c == '(':
			depth++
		case c == ')':
			depth--
			if depth < 0 {
				return false
			}
		}
	}
	return depth == 0 && !class
}

// truthy is Python's bool() of a tacctl.yaml value.
func truthy(v any) bool {
	switch x := v.(type) {
	case nil:
		return false
	case bool:
		return x
	case string:
		return x != ""
	case float64:
		return x != 0
	case *yamlpy.Map:
		return x.Len() > 0
	}
	if b := py.BigInt(v); b != nil {
		return b.Sign() != 0
	}
	if l, ok := py.List(v); ok {
		return len(l) > 0
	}
	return true
}

func get(v any, key string) (any, bool) {
	m, ok := v.(*yamlpy.Map)
	if !ok {
		return nil, false
	}
	return m.Get(key)
}

// GroupCommands is group_commands: commands.<group> of the merged
// tacctl.yaml view as validated rules.
func GroupCommands(view *yamlpy.Map, group string) ([]Rule, error) {
	cmds, _ := view.Get("commands")
	if !truthy(cmds) {
		return nil, nil
	}
	if _, ok := cmds.(*yamlpy.Map); !ok {
		// 0.1.16 died with a Python traceback here.
		return nil, &rendered.Error{Msg: "tacctl.yaml: commands is not a mapping of groups"}
	}
	rules, _ := get(cmds, group)
	if !truthy(rules) {
		return nil, nil
	}
	list, ok := py.List(rules)
	if !ok {
		return nil, &rendered.Error{Msg: fmt.Sprintf("tacctl.yaml: commands.%s is not a list of rules", group)}
	}
	var out []Rule
	for _, r := range list {
		nameV, _ := get(r, "name")
		name, isStr := nameV.(string)
		if _, isMap := r.(*yamlpy.Map); !isMap || !isStr || name == "" {
			return nil, &rendered.Error{Msg: fmt.Sprintf("tacctl.yaml: commands.%s has a rule without a name", group)}
		}
		actionV, has := get(r, "action")
		if !has {
			actionV = "permit"
		}
		action, isStr := actionV.(string)
		if _, known := Actions[action]; !isStr || !known {
			return nil, &rendered.Error{Msg: fmt.Sprintf("tacctl.yaml: commands.%s: rule '%s' has an action that is neither permit nor deny", group, name)}
		}
		matchV, _ := get(r, "match")
		var match []string
		if truthy(matchV) {
			items, isList := py.List(matchV)
			if !isList {
				return nil, &rendered.Error{Msg: fmt.Sprintf("tacctl.yaml: commands.%s: rule '%s' has a match that is not a list of strings", group, name)}
			}
			for _, m := range items {
				s, isStr := m.(string)
				if !isStr {
					return nil, &rendered.Error{Msg: fmt.Sprintf("tacctl.yaml: commands.%s: rule '%s' has a match that is not a list of strings", group, name)}
				}
				match = append(match, s)
			}
		}
		out = append(out, Rule{Name: name, Action: action, Match: match})
	}
	return out, nil
}

// RenderedHash is rendered_hash: what goes in the file for a user, the
// real hash or the marker nothing matches.
func RenderedHash(u *model.User) string {
	if u.IsDisabled() {
		return hash.DisabledMarkerHex
	}
	return u.Hash
}

func isDigits(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

// cidrKey is cidr_key of a CIDR the validator accepted.
func cidrKey(c string) cidr.Key {
	k, _ := cidr.SortKey(c)
	return k
}

// sortCIDRs is sorted(items, key=cidr_key) (stable).
func sortCIDRs(items []string) []string {
	out := slices.Clone(items)
	sort.SliceStable(out, func(i, j int) bool { return cidrKey(out[i]).Less(cidrKey(out[j])) })
	return out
}

func privText(g *model.Group) string {
	if g.PrivLvl == nil {
		return "None"
	}
	return strconv.Itoa(*g.PrivLvl)
}

// Render is render_tacacs: the store and the merged tacctl.yaml view ->
// the text of tacquito.yaml. A store that does not validate is refused
// with every problem ('cannot render an invalid model: ...'), and so is a
// command rule of tacctl.yaml that is not one. hostNames are the enrolled
// hosts (hosts.EnrolledNames): a hold on one is worded as a host in the
// comment block. server is where this server is enrolled
// (pwchange.LocalServer): the one scope a user who must change the password
// keeps. The output depends only on the inputs, so an unchanged model renders
// byte-identically.
func Render(st *store.Store, view *yamlpy.Map, hostNames map[string]bool, server pwchange.Server) ([]byte, error) {
	if errs := store.Validate(st.Doc()); len(errs) > 0 {
		return nil, &rendered.Error{Msg: "cannot render an invalid model:\n  - " + strings.Join(errs, "\n  - ")}
	}
	m := model.FromStore(st)
	// The break-glass holds of tacctl.yaml: their addresses are taken out
	// of every prefix below, for the comment block and the entries
	// (docs/plans/0.2.5-plan.md D123); the store is not changed.
	holds := conf.HoldsOf(view)
	whole := m
	m = Carved(m, view, server)
	var w strings.Builder

	w.WriteString(Header)
	w.WriteString("\n# --- Type constants ---\n" +
		"authenticator_type_bcrypt: &authenticator_type_bcrypt 1\n" +
		"action_deny:  &action_deny  1\n" +
		"action_permit: &action_permit 2\n" +
		"accounter_type_file: &accounter_type_file 3\n" +
		"handler_type_start: &handler_type_start 1\n" +
		"provider_type_prefix: &provider_type_prefix 1\n" +
		"\n# --- Accounting ---\n" +
		"file_accounter: &file_accounter\n" +
		"  name: tacquito_accounter\n" +
		"  type: *accounter_type_file\n" +
		"\n# --- Per-user bcrypt authenticators ---\n" +
		"# A disabled account and the 'root' accounting sink carry a well-formed\n" +
		"# hash that no password matches.\n")
	anchors := userAnchors(m.Users)
	for i, u := range m.Users {
		h := RenderedHash(u)
		// All-digit hex would read as a number; nothing else needs quotes.
		if isDigits(h) {
			h = YQ(h)
		}
		fmt.Fprintf(&w, "\nbcrypt_%s: &bcrypt_%s\n"+
			"  type: *authenticator_type_bcrypt\n"+
			"  options:\n"+
			"    hash: %s\n", anchors[i], anchors[i], h)
	}

	w.WriteString("\n# --- Services ---\n" +
		"# Cisco IOS/IOS-XE sends service=shell for exec authorization and expects\n" +
		"# priv-lvl; the anchors keep 'exec' as the label for the tier.\n" +
		"# Juniper requests service=junos-exec and expects local-user-name.\n" +
		"# Each device type only requests its own service; the other is ignored.\n")
	order := GroupOrder(m.GroupNames())
	cfg := conf.View(view)
	sets := make(map[string]string, len(order))
	devauth := false
	for _, name := range order {
		v, err := junosSetValues(cfg, name)
		if err != nil {
			return nil, err
		}
		sets[name] = v
		_, over := policy.WTILevel(cfg, name, 0)
		devauth = devauth || v != "" || over
	}
	// Only when a group uses them, so a model without these settings
	// renders byte-identically to 0.2.1.
	if devauth {
		w.WriteString("# A WTI unit with Service Name 'wti' requests service=wti (a group with a\n" +
			"# WTI level of its own); deny-* are the Junos deny sets of the group.\n")
	}
	for _, name := range order {
		g := m.Group(name)
		p := privText(g)
		fmt.Fprintf(&w, "\n# Cisco exec - %s (priv-lvl %s)\n"+
			"exec_%s: &exec_%s\n"+
			"  name: shell\n"+
			"  set_values:\n"+
			"    - name: priv-lvl\n"+
			"      values: [%s]\n"+
			"\n# Juniper junos-exec - %s\n"+
			"# \"%s\" must match a local template user on Juniper devices\n"+
			"junos_exec_%s: &junos_exec_%s\n"+
			"  name: junos-exec\n"+
			"  set_values:\n"+
			"    - name: local-user-name\n"+
			"      values: [%s]\n%s",
			name, p, name, name, p, name, g.JuniperClass, name, name, YQ(g.JuniperClass), sets[name])
		if level, over := policy.WTILevel(cfg, name, 0); over {
			lv := policy.WTIPrivLvl(level)
			_, label := radius.WTISuper(lv)
			fmt.Fprintf(&w, "\n# WTI wti - %s (priv-lvl %d, %s; 'tacctl group edit %s wti-level')\n"+
				"wti_exec_%s: &wti_exec_%s\n"+
				"  name: wti\n"+
				"  set_values:\n"+
				"    - name: priv-lvl\n"+
				"      values: [%d]\n",
				name, lv, label, name, name, name, lv)
		}
	}

	w.WriteString("\n# --- Groups ---\n" +
		"# Command rules come from commands.<group> in tacctl.yaml.\n")
	for i, name := range order {
		key := GroupKey(name)
		if i > 0 {
			w.WriteByte('\n')
		}
		fmt.Fprintf(&w, "%s: &%s\n"+
			"  name: %s\n"+
			"  services:\n"+
			"    - *exec_%s\n"+
			"    - *junos_exec_%s\n", YName(key), key, YName(name), name, name)
		if _, over := policy.WTILevel(cfg, name, 0); over {
			fmt.Fprintf(&w, "    - *wti_exec_%s\n", name)
		}
		rules, err := GroupCommands(view, name)
		if err != nil {
			return nil, err
		}
		if len(rules) > 0 {
			w.WriteString("  commands:\n")
			for _, r := range rules {
				fmt.Fprintf(&w, "    - name: %s\n", YQ(r.Name))
				if len(r.Match) > 0 {
					q := make([]string, len(r.Match))
					for i, s := range r.Match {
						q[i] = YQ(renderMatch(s))
					}
					w.WriteString("      match: [" + strings.Join(q, ", ") + "]\n")
				}
				fmt.Fprintf(&w, "      action: *action_%s\n", r.Action)
			}
		}
		w.WriteString("  accounter: *file_accounter\n")
	}

	w.WriteString("\n# --- Users ---\n")
	for _, l := range carvedLines(whole, view, server) {
		w.WriteString(l + "\n")
	}
	if len(m.Users) > 0 {
		w.WriteString("users:\n")
		for i, u := range m.Users {
			var mine []string
			for _, s := range u.Scopes {
				if sc := m.Scope(s); sc != nil && sc.ServedBy(Protocol) {
					mine = append(mine, YQ(s))
				}
			}
			fmt.Fprintf(&w, "\n  # %s\n"+
				"  - name: %s\n"+
				"    scopes: [%s]\n"+
				"    groups: [*%s]\n"+
				"    authenticator: *bcrypt_%s\n"+
				"    accounter: *file_accounter\n",
				u.Name, YName(u.Name), strings.Join(mine, ", "), GroupKey(u.Group), anchors[i])
		}
	} else {
		w.WriteString("users: []\n")
	}

	w.WriteString("\n# --- Secret Providers (Scopes) ---\n" +
		"# One entry per (scope, prefix), most specific prefix first: tacquito\n" +
		"# answers a client with the first entry whose prefix contains it.\n")
	w.WriteString(holdComment(whole, holds, hostNames))
	type entry struct {
		cidr, scope string
		key         cidr.Key
	}
	var entries []entry
	for _, sc := range m.Scopes {
		if !sc.ServedBy(Protocol) {
			continue
		}
		for i, c := range sc.Prefixes {
			// A piece carved out of a prefix sorts where that prefix did.
			entries = append(entries, entry{c, sc.Name, cidrKey(sc.PrefixOrigin(i))})
		}
	}
	sort.SliceStable(entries, func(i, j int) bool {
		a, b := entries[i], entries[j]
		if a.key != b.key {
			return a.key.Less(b.key)
		}
		return a.scope < b.scope
	})
	// A piece two prefixes of a scope both produce is one entry, the one
	// that sorts first (only a carve makes one).
	if len(holds) > 0 {
		seen := map[[2]string]bool{}
		kept := entries[:0]
		for _, e := range entries {
			k := [2]string{e.scope, e.cidr}
			if seen[k] {
				continue
			}
			seen[k] = true
			kept = append(kept, e)
		}
		entries = kept
	}
	if len(entries) > 0 {
		w.WriteString("secrets:\n")
		for _, e := range entries {
			cj, _ := py.Dumps(e.cidr)
			fmt.Fprintf(&w, "  - name: %s\n"+
				"    secret:\n"+
				"      group: tacquito\n"+
				"      key: %s\n"+
				"    handler:\n"+
				"      type: *handler_type_start\n"+
				"    type: *provider_type_prefix\n"+
				"    options:\n"+
				"      prefixes: |\n"+
				"        [\n"+
				"          %s\n"+
				"        ]\n", YName(e.scope), YQ(m.Scope(e.scope).Secret), cj)
		}
	} else {
		w.WriteString("secrets: []\n")
	}

	var lines []string
	for _, f := range []struct {
		items []string
		key   string
	}{{m.Filters.Allow, "prefix_allow"}, {m.Filters.Deny, "prefix_deny"}} {
		items := sortCIDRs(f.items)
		if len(items) > 0 {
			q := make([]string, len(items))
			for i, c := range items {
				q[i] = YQ(c)
			}
			lines = append(lines, f.key+": ["+strings.Join(q, ", ")+"]\n")
		}
	}
	if len(lines) > 0 {
		w.WriteString("\n# --- Connection filters ---\n" + strings.Join(lines, ""))
	}
	return []byte(w.String()), nil
}

// Carved is the model with every user in the scope of this server's own
// logins when tacctl manages it (pwchange.WithServerScope), without the
// addresses of the holds of the merged
// view (model.WithoutAddresses), without the members of a locked group in
// the scope that locks them, and with a user who must change the password
// in this server's own scope only (pwchange.Carve): the model the renderer
// writes and the read-back compares the file with.
func Carved(m *model.Model, view *yamlpy.Map, server pwchange.Server) *model.Model {
	// every user is in the scope tacctl manages for this server's own logins
	// (0.2.21), before the lockdown and the password change cut scopes out
	m = pwchange.WithServerScopeView(view, m, server)
	// the members of a locked group are taken out of the scope that locks it
	// (0.2.19, the emergency lockdown)
	m = m.WithoutAddresses(conf.HeldAddresses(view)).WithoutMembers(conf.LockedGroups(view))
	// a user who must change the password is in no scope but this server's
	// own (0.2.20): no device authenticates them until they have changed it
	return pwchange.Carve(m, view, Protocol, server)
}

// carvedLines are the comments of the users section naming the users cut out
// of scopes they have in the store: by an emergency lockdown (the members of a
// locked group) and by a required password change. The import of the file
// reads them (store.CarvedUsers): it holds neither the scopes nor the
// requirement. A user counts when the scopes this file shows for the user
// changed, so one cut only in scopes of the other protocol is not named.
func carvedLines(m *model.Model, view *yamlpy.Map, server pwchange.Server) []string {
	base := pwchange.WithServerScopeView(view, m, server).WithoutAddresses(conf.HeldAddresses(view))
	locked := base.WithoutMembers(conf.LockedGroups(view))
	final := pwchange.Carve(locked, view, Protocol, server)
	shown := func(mm *model.Model, u *model.User) []string {
		var out []string
		for _, s := range u.Scopes {
			if sc := mm.Scope(s); sc != nil && sc.ServedBy(Protocol) {
				out = append(out, s)
			}
		}
		return out
	}
	diff := func(a, b *model.Model) []string {
		var out []string
		for _, u := range a.Users {
			if nu := b.User(u.Name); nu != nil && !slices.Equal(shown(a, u), shown(b, nu)) {
				out = append(out, u.Name)
			}
		}
		return out
	}
	var lines []string
	if u := diff(base, locked); len(u) > 0 {
		lines = append(lines, store.CarvedLine(store.CarvedLockdown, Protocol, u))
	}
	if u := diff(locked, final); len(u) > 0 {
		lines = append(lines, store.CarvedLine(store.CarvedPasswordChange, Protocol, u))
	}
	return lines
}

// holdComment is the comment block of the secret providers naming each
// held address, its device or host (a name in hostNames is a host) and the
// prefixes it was carved out of (the stored ones of the scopes this backend
// serves), "" when no hold carves anything out of this file. Never the
// reason: free text does not go into a backend file.
func holdComment(m *model.Model, holds []conf.Hold, hostNames map[string]bool) string {
	var b strings.Builder
	for _, h := range holds {
		from := m.CarvedFrom(h.Address, Protocol, false)
		if len(from) == 0 {
			continue
		}
		parts := make([]string, len(from))
		for i, c := range from {
			parts[i] = c.CIDR + " (" + c.Scope + ")"
		}
		fmt.Fprintf(&b, "# break-glass held: %s (%s %s) is answered by no entry; carved out of %s\n",
			h.Address, conf.HoldKind(h.Device, hostNames), h.Device, strings.Join(parts, ", "))
	}
	if b.Len() == 0 {
		return ""
	}
	return "# Break-glass holds ('tacctl breakglass list'): the addresses below are taken out of the\n" +
		"# prefixes that cover them, so this server does not answer them. A piece carved out of a\n" +
		"# prefix is listed where that prefix was, so every other address keeps the scope it had.\n" + b.String()
}

// junosSetValues is the set_values lines the group's Junos deny sets add
// to its junos-exec service ("" for a group without any). A set whose
// value would not fit in one TACACS+ argument stops the render: Junos
// would refuse every login of the group.
func junosSetValues(cfg *conf.Config, group string) (string, error) {
	var b strings.Builder
	for _, attr := range conf.JunosAttrs {
		items := policy.JunosSet(cfg, group, attr)
		if len(items) == 0 {
			continue
		}
		if p := policy.JunosProblem(group, attr, items); p != nil {
			return "", &rendered.Error{Msg: "cannot render tacquito.yaml: " + strings.Join(p, "\n  ")}
		}
		fmt.Fprintf(&b, "    - name: %s\n      values: [%s]\n", conf.JunosArg(attr), YQ(conf.JunosValue(items)))
	}
	return b.String(), nil
}

// isLevel is is_int(level) and 0 <= level <= 100.
func isLevel(v any) bool {
	b := py.BigInt(v)
	return b != nil && b.Sign() >= 0 && b.Cmp(big.NewInt(100)) <= 0
}
