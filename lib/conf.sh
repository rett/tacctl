# =====================================================================
#  Unified config (tacctl.yaml + in-script defaults)
# =====================================================================
#
# Canonical defaults live in conf_emit_defaults() below — the single
# source of truth for shipped tunables. Operator overrides live in
# $TACCTL_OVERRIDES_FILE (default /etc/tacquito/tacctl.yaml); only keys
# the operator has changed appear there.
#
# Reads deep-merge the two (scalars + lists override, maps union-merge),
# cached once per invocation in $_TACCTL_CFG_CACHE (merged JSON string).
# Writes mutate the overrides file and invalidate the cache. A write
# equal to the default removes the key (revert-to-default); an overrides
# file with no keys left is pruned.
#
#   conf_get <dotted.path> [fallback]           -> scalar, one line
#   conf_get_list <dotted.path>                 -> newline-joined list
#   conf_get_keys <dotted.path>                 -> keys of a map, one per line
#   conf_set <dotted.path> <value>              -> scalar write
#   conf_set_list <dotted.path> [newline-items] -> list write (items on stdin)
#   conf_unset <dotted.path>                    -> delete key from overrides
#   conf_emit_defaults                          -> canonical defaults as YAML
#   conf_is_default <dotted.path> <value>       -> 0 if value equals default

# --- Canonical defaults ---
# The ONE source of truth for shipped tunables. Every entry here is also
# validated by _CONF_SCHEMA below; add new tunables in both places.
conf_emit_defaults() {
    cat <<'YAML'
# tacctl canonical defaults (emitted by `tacctl config defaults`).
# DO NOT edit this output — it is generated by conf_emit_defaults() in
# bin/tacctl.sh. Override any key in /etc/tacquito/tacctl.yaml.

password:
  max_age_days: 90        # warning threshold used by `tacctl status`
  min_length: 12          # floor for interactively-typed passwords

secret:
  min_length: 16          # floor for operator-typed shared secrets

bcrypt:
  cost: 12                # applies to new hashes; range 10..14

scope:
  default: lab            # matches the fresh-install seed scope; override via `tacctl scope default <name>`

host:
  default_method: tacplus # how `tacctl host enroll` sets up a new Linux host: tacplus | radius

mgmt_acl:
  names:
    cisco: VTY-ACL        # ACL name emitted by `tacctl config cisco`
    juniper: MGMT-ACL # filter name emitted by `tacctl config juniper`
  permits: []             # CIDRs for Cisco VTY-ACL + Juniper lo0 filter

privileges:
  # Per-group Cisco priv-exec lists. Shipped defaults move only
  # verified priv-15 commands DOWN to lower-privilege groups; they
  # never move commands UP from a lower default level (which would
  # silently restrict readonly users). Override any list in tacctl.yaml.
  operator:
    # Shipped priv-15 read/diagnostic commands lowered to priv-7 so
    # commands.operator's `show` permit is actually reachable for
    # common read paths. No write/configure/debug included.
    - show running-config
    - show startup-config
    - show tech-support
    - show archive
    - show access-list
    - show ip route

commands:
  # Per-group per-command authorization rules. tacctl.yaml is the ONE
  # source of truth; tacquito.yaml's per-group `commands:` block is
  # regenerated from this section on every mutation, and
  # `tacctl config juniper` renders the same rules as class-level
  # allow-commands / deny-commands for Junos.
  #
  # Each rule: {name, action: permit|deny, match: [regex, ...]}
  # `name` is compared literally against the TACACS+ cmd= word. `match`
  # regexes are applied by tacquito to the command's ARGUMENTS only —
  # the space-joined cmd-arg values after the cmd word, e.g. for
  # `show running-config` the string tested is `running-config`, not
  # the full line. A regex that repeats the command word (`^show .*$`)
  # can therefore never match and silently denies every invocation.
  # Omit `match` to permit/deny the command with any arguments.
  # A trailing name: "*" entry is the catch-all; its action is the
  # group's default action.
  #
  # Ordered superuser → operator → readonly to match how a reader scans
  # privilege from most-to-least permissive.
  superuser:
    # Priv 15 + RW-CLASS — unrestricted by policy.
    - { name: "*", action: permit }
  operator:
    # Read-only + diagnostics; everything else (configure, write,
    # debug, reload, etc.) hits the deny catch-all.
    - { name: show,       action: permit }
    - { name: ping,       action: permit }
    - { name: traceroute, action: permit }
    - { name: terminal,   action: permit }
    - { name: "*",        action: deny }
  readonly:
    # Defense in depth on top of priv-1 / RO-CLASS. Permits are the
    # read / diagnostic subset of operator's; `terminal` is omitted
    # (terminal monitor can leak debug output across sessions).
    - { name: show,       action: permit }
    - { name: ping,       action: permit }
    - { name: traceroute, action: permit }
    - { name: "*",        action: deny }
YAML
}

# --- Cache control ---------------------------------------------------------
# _TACCTL_CFG_CACHE holds the merged defaults+overrides as a JSON string.
# Empty = cold cache (next read re-merges). _conf_invalidate is called from
# every write path so subsequent reads see the mutation.
_TACCTL_CFG_CACHE=""
# It also drops the list of enabled backends (lib/backend.sh), which is read
# from the same file.
_conf_invalidate() { _TACCTL_CFG_CACHE=""; _BACKENDS_LOADED=0; }

_conf_load_cache() {
    [[ -n "$_TACCTL_CFG_CACHE" ]] && return 0
    # One python invocation: load defaults (from conf_emit_defaults output
    # on a throwaway fd) + overrides file, deep-merge, dump as JSON to
    # stdout. The merged JSON stays small (<2 KB for typical installs).
    _TACCTL_CFG_CACHE=$(python3 - <(conf_emit_defaults) "${TACCTL_OVERRIDES_FILE:-}" <<'PY'
import json, os, sys, yaml
defaults_path, overrides_path = sys.argv[1:3]
def load(p):
    if p and os.path.exists(p):
        try:
            with open(p) as f:
                return yaml.safe_load(f) or {}
        except Exception:
            return {}
    return {}
def merge(a, b):
    out = dict(a)
    for k, v in (b or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = merge(out[k], v)
        else:
            out[k] = v
    return out
print(json.dumps(merge(load(defaults_path), load(overrides_path))))
PY
)
}

# Walk the cached merged view along a dotted path.
# mode: get | get_list | get_keys.
_conf_walk() {
    local mode="$1" path="$2" fallback="${3:-}"
    _conf_load_cache
    python3 -c '
import json, sys
data = json.loads(sys.argv[1])
mode, path, fallback = sys.argv[2], sys.argv[3], sys.argv[4]
cur = data
for part in (path.split(".") if path else []):
    if isinstance(cur, dict) and part in cur:
        cur = cur[part]
    else:
        cur = None
        break
if mode == "get":
    if cur is None:
        print(fallback)
    elif isinstance(cur, bool):
        print("true" if cur else "false")
    elif isinstance(cur, (list, dict)):
        pass  # caller should use get_list / get_keys
    else:
        print(cur)
elif mode == "get_list":
    if isinstance(cur, list):
        for item in cur:
            print(item)
elif mode == "get_keys":
    if isinstance(cur, dict):
        for k in cur.keys():
            print(k)
' "$_TACCTL_CFG_CACHE" "$mode" "$path" "$fallback"
}

conf_get()      { _conf_walk get      "$1" "${2:-}"; }
conf_get_list() { _conf_walk get_list "$1"; }
conf_get_keys() { _conf_walk get_keys "$1"; }

# --- Schema for write-time validation --------------------------------------
# The ONE source of truth for what's legal in tacctl.yaml. Emitted as a
# Python literal so both _conf_write (mutation-time) and
# _conf_validate_overrides_file (scan-time) can import it unchanged.
#
# Types: int (with optional min/max), string (with optional regex pattern
# + optional max_length), nullable_string (string or null), cidr_list,
# cisco_cmd_list, backend_list, host_port, listener, string_scalar. The
# `pattern` is a Python regex.

# --- Listener model (plan 3.4) ---------------------------------------------
# listeners.<backend>.<name> in tacctl.yaml says where a backend's daemon
# listens:
#
#   listeners:
#     tacacs:
#       default: { network: tcp, address: ":49" }
#       mgmt:    { network: tcp, address: "10.1.0.1:4949" }
#
# Keys: network (tcp|tcp6|udp|udp6), address (host:port, [v6]:port or :port),
# role (auth|acct|both), metrics_address (host:port; a daemon that exports
# metrics per process), and tls {enabled, cert, key, ca,
# require_client_cert}. The tls block is reserved: its fields are accepted so
# that TACACS+ over TLS needs no schema change, and 'enabled: true' is
# refused until a release implements it.
#
# LISTENER_BACKENDS says what each backend's daemon can do and which
# listeners exist without being written down ('defaults'); a listener named
# there can be changed and reset but not removed. Python shared by the schema
# below and by the backends' renderers.
_listener_py() {
    cat <<'PY'
import ipaddress, re

LISTENER_BACKENDS = {
    # One tacquito process serves one stream listener, authentication and
    # accounting together.
    'tacacs': {'networks': ('tcp', 'tcp6'), 'roles': ('both',),
               'defaults': {'default': {'network': 'tcp', 'address': ':49'}}},
    # One FreeRADIUS process serves every listener; a listener answers
    # authentication or accounting, never both (a listener written without a
    # role is an authentication one).
    'radius': {'networks': ('udp', 'udp6'), 'roles': ('acct', 'auth'),
               'defaults': {'auth': {'network': 'udp', 'address': ':1812', 'role': 'auth'},
                            'acct': {'network': 'udp', 'address': ':1813', 'role': 'acct'}}},
}
LISTENER_NETWORKS = ('tcp', 'tcp6', 'udp', 'udp6')
LISTENER_ROLES = ('auth', 'acct', 'both')
LISTENER_KEYS = ('network', 'address', 'role', 'metrics_address', 'tls')
LISTENER_TLS_KEYS = ('enabled', 'cert', 'key', 'ca', 'require_client_cert')
RE_LISTENER_NAME = re.compile(r'[a-z][a-z0-9_-]{0,31}')
RE_HOST_PORT = re.compile(r'(\[[0-9A-Fa-f:.]+\]|[A-Za-z0-9.-]*):([0-9]{1,5})')
WILDCARD_HOSTS = ('', '0.0.0.0', '::')


def split_listen_address(addr):
    """'host:port' or '[v6]:port' -> (host, port); None when it is neither."""
    if not isinstance(addr, str):
        return None
    m = re.fullmatch(r'\[([^\]]+)\]:(\d+)', addr) or re.fullmatch(r'([^:]*):(\d+)', addr)
    if not m:
        return None
    return m.group(1), int(m.group(2))


def listen_address_problem(network, addr):
    """'' when addr is a listen address of the network's family, else why not.
    The host is empty (every address) or an IP literal, never a name."""
    parts = split_listen_address(addr)
    if parts is None:
        return 'must be host:port, [ipv6]:port or :port'
    host, port = parts
    if not 1 <= port <= 65535:
        return 'port must be 1..65535'
    if host:
        try:
            ip = ipaddress.ip_address(host)
        except ValueError:
            return f'{host!r} is not an IP address'
        if network in ('tcp', 'udp') and ip.version != 4:
            return f'{network} takes an IPv4 address ({network}6 for IPv6)'
        if network in ('tcp6', 'udp6') and ip.version != 6:
            return f'{network} takes an IPv6 address in brackets'
    return ''


def host_port_problem(value):
    """'' when value is host:port (host may be empty or a name; port 0 is
    the kernel's choice), else why not."""
    if not isinstance(value, str):
        return 'must be a string host:port'
    m = RE_HOST_PORT.fullmatch(value)
    if not m:
        return "must be host:port (e.g. '127.0.0.1:8080' or ':8080')"
    if int(m.group(2)) > 65535:
        return 'port must be 0..65535'
    return ''


def listener_normalize(backend, value):
    """Every key present, defaults filled in. value must have passed
    listener_problem."""
    spec = LISTENER_BACKENDS[backend]
    tls = value.get('tls') or {}
    return {
        'network': value.get('network') or spec['networks'][0],
        'address': value['address'],
        'role': value.get('role') or spec['roles'][-1],
        'metrics_address': value.get('metrics_address') or '',
        'tls': {
            'enabled': False,
            'cert': tls.get('cert') or '',
            'key': tls.get('key') or '',
            'ca': tls.get('ca') or '',
            'require_client_cert': bool(tls.get('require_client_cert')),
        },
    }


def listener_compact(backend, value):
    """What tacctl.yaml stores: only what differs from the defaults."""
    spec = LISTENER_BACKENDS[backend]
    full = listener_normalize(backend, value)
    out = {'network': full['network'], 'address': full['address']}
    if full['role'] != spec['roles'][-1]:
        out['role'] = full['role']
    if full['metrics_address']:
        out['metrics_address'] = full['metrics_address']
    tls = {k: v for k, v in full['tls'].items() if v}
    if tls:
        out['tls'] = tls
    return out


def listener_problem(backend, name, value):
    """'' when value is a valid listeners.<backend>.<name>, else why not."""
    spec = LISTENER_BACKENDS.get(backend)
    if spec is None:
        return f"'{backend}' is not a backend with listeners (known: {', '.join(LISTENER_BACKENDS)})"
    if not RE_LISTENER_NAME.fullmatch(name):
        return 'a listener name is a lowercase letter, then up to 31 of [a-z0-9_-]'
    if not isinstance(value, dict):
        return 'must be a mapping {network, address, role?, metrics_address?, tls?}'
    extra = sorted(set(value) - set(LISTENER_KEYS))
    if extra:
        return f"unknown keys {extra} (known: {', '.join(LISTENER_KEYS)})"
    network = value.get('network', spec['networks'][0])
    if network not in LISTENER_NETWORKS:
        return f"network must be one of {', '.join(LISTENER_NETWORKS)} (got {network!r})"
    if network not in spec['networks']:
        return f"the {backend} backend listens on {' or '.join(spec['networks'])} only (got {network})"
    if 'address' not in value:
        return 'address is required'
    why = listen_address_problem(network, value['address'])
    if why:
        return f"address {value['address']!r}: {why}"
    role = value.get('role', spec['roles'][-1])
    if role not in LISTENER_ROLES:
        return f"role must be one of {', '.join(LISTENER_ROLES)} (got {role!r})"
    if role not in spec['roles']:
        return f"a {backend} listener has role {' or '.join(spec['roles'])} (got {role})"
    if value.get('metrics_address') not in (None, ''):
        why = host_port_problem(value['metrics_address'])
        if why:
            return f'metrics_address: {why}'
    tls = value.get('tls')
    if tls is not None:
        if not isinstance(tls, dict):
            return f"tls must be a mapping {{{', '.join(LISTENER_TLS_KEYS)}}}"
        extra = sorted(set(tls) - set(LISTENER_TLS_KEYS))
        if extra:
            return f"tls: unknown keys {extra} (known: {', '.join(LISTENER_TLS_KEYS)})"
        for k in ('enabled', 'require_client_cert'):
            if not isinstance(tls.get(k, False), bool):
                return f'tls.{k} must be true or false'
        for k in ('cert', 'key', 'ca'):
            if not isinstance(tls.get(k, ''), str):
                return f'tls.{k} must be a file path'
        if tls.get('enabled'):
            return 'tls.enabled: true is reserved for a future release (TLS listeners are not implemented)'
    return ''


def listeners_effective(doc, backend):
    """{name: normalized listener} for one backend: the built-in ones
    (as overridden), then the others by name. An entry that does not
    validate is left out, or falls back to the built-in one of its name;
    listeners_problems names it."""
    spec = LISTENER_BACKENDS.get(backend) or {'defaults': {}}
    section = ((doc or {}).get('listeners') or {})
    mine = section.get(backend) if isinstance(section, dict) else None
    mine = mine if isinstance(mine, dict) else {}
    out = {}
    for name in list(spec['defaults']) + sorted(n for n in mine if isinstance(n, str) and n not in spec['defaults']):
        value = mine.get(name)
        if value is None or listener_problem(backend, name, value):
            value = spec['defaults'].get(name)
        if value is not None:
            out[name] = listener_normalize(backend, value)
    return out


def _binds_collide(a, b):
    """Two listeners that cannot both bind: same transport and port, and
    the same host or a wildcard on either side (':49' is every address of
    both families)."""
    if a['network'][:3] != b['network'][:3]:
        return False
    # FreeRADIUS, the one udp daemon, binds a socket per family: udp ':1812'
    # is IPv4 only and does not take the port from a udp6 listener.
    if a['network'][:3] == 'udp' and a['network'] != b['network']:
        return False
    (ha, pa), (hb, pb) = split_listen_address(a['address']), split_listen_address(b['address'])
    if pa != pb:
        return False
    if ha in WILDCARD_HOSTS or hb in WILDCARD_HOSTS:
        return True
    return ipaddress.ip_address(ha) == ipaddress.ip_address(hb)


def listeners_problems(doc, only=None):
    """Every problem of the listeners section of a tacctl.yaml document, as
    '<path>: <reason>' strings: invalid entries, and two listeners (of any
    backends) on one network and address. With only=<path>, the problems of
    that one listener, a collision told from its side."""
    problems = []
    section = (doc or {}).get('listeners')
    if section is None:
        section = {}
    if not isinstance(section, dict):
        return ['listeners: must be a mapping of backends']
    for backend, mine in section.items():
        if not isinstance(mine, dict):
            problems.append(f'listeners.{backend}: must be a mapping of listener names')
            continue
        for name, value in mine.items():
            why = listener_problem(str(backend), str(name), value)
            if why:
                problems.append(f'listeners.{backend}.{name}: {why}')
    if only is not None:
        problems = [p for p in problems if p.startswith(only + ':')]
    seen = []
    for backend in LISTENER_BACKENDS:
        for name, l in listeners_effective(doc, backend).items():
            path = f'listeners.{backend}.{name}'
            for other_path, other in seen:
                if only is not None and only not in (path, other_path):
                    continue
                # Told from the later listener's side, or from only's.
                (pa, a), (pb, b) = ((other_path, other), (path, l)) if only == other_path else ((path, l), (other_path, other))
                if _binds_collide(a, b):
                    problems.append(f"{pa}: {a['network']} {a['address']} is already used by {pb} ({b['network']} {b['address']})")
                if a['metrics_address'] and a['metrics_address'] == b['metrics_address'] \
                        and not a['metrics_address'].endswith(':0'):
                    problems.append(f"{pa}: metrics_address {a['metrics_address']} is already used by {pb}")
            seen.append((path, l))
    return problems

PY
}

