    local ids="" id
    for id in ${BACKEND_IDS[@]+"${BACKEND_IDS[@]}"}; do
        ids+="${ids:+, }'${id}'"
    done
    sed "s/@BACKEND_IDS@/[${ids}]/" <<'PY'
SCHEMA = {
    'password.max_age_days': {'type': 'int', 'min': 1},
    'password.min_length':   {'type': 'int', 'min': 8,  'max': 64},
    'secret.min_length':     {'type': 'int', 'min': 16, 'max': 128},
    'bcrypt.cost':           {'type': 'int', 'min': 10, 'max': 14},
    'scope.default':         {'type': 'nullable_string',
                              'pattern': r'^[a-zA-Z][a-zA-Z0-9_-]{0,31}$'},
    'host.default_method':   {'type': 'enum', 'values': ['tacplus', 'radius']},
    'mgmt_acl.names.cisco':  {'type': 'acl_name'},
    'mgmt_acl.names.juniper':{'type': 'acl_name'},
    'mgmt_acl.permits':      {'type': 'cidr_list'},
    # Backends that serve the model, in render and restart order. 'values' is
    # the registry (BACKEND_IDS, lib/backend.sh: every module in lib/backends/
    # registers itself), substituted when the schema is emitted, so a new
    # module needs no edit here. Not in conf_emit_defaults: 'default' below is
    # the shipped value, as for the wildcard entries, and
    # BACKENDS_DEFAULT_ENABLED in lib/backend.sh mirrors it (a unit test pins
    # both).
    'backends.enabled':      {'type': 'backend_list',
                              'values': @BACKEND_IDS@,
                              'default': ['tacacs']},
    # Per-backend daemon settings ('tacctl config loglevel|metrics'). They
    # apply to every listener's process; tacquito takes 10 (error), 20 (info)
    # or 30 (debug). The metrics address is the default listener's; another
    # listener exports metrics only when it sets metrics_address itself.
    'backends.tacacs.level': {'type': 'int', 'min': 0, 'max': 100, 'default': 20},
    'backends.tacacs.metrics_address':
                             {'type': 'host_port', 'default': '127.0.0.1:8080'},
}
# Wildcard paths: each operator-created group/scope gets its own entry
# under privileges.<group>, commands.<group>, aaa.order.<scope>. The
# matcher below accepts any lowercase-start name as the single trailing
# path segment and validates the value against the rule type.
WILDCARDS = [
    ('privileges.',   {'type': 'cisco_cmd_list'}),
    ('commands.',     {'type': 'command_rules'}),
    ('aaa.order.',    {'type': 'enum',
                       'values': ['tacacs-first', 'local-first'],
                       # Implicit per-instance default. _conf_write uses
                       # this to prune the override when the set value
                       # matches (scopes aren't pre-enumerated in
                       # conf_emit_defaults, so we can't rely on
                       # get_nested(defaults, ...) to tell us the default).
                       'default': 'tacacs-first'}),
    ('exec_timeout.', {'type': 'int',
                       # 0 = never expire (Cisco: `exec-timeout 0 0`).
                       # Junos `idle-timeout` max is 60 minutes, so the
                       # upper bound is set to what both vendors accept
                       # cleanly with one knob.
                       'min': 0, 'max': 60,
                       'default': 60}),
    ('tacacs_group.', {'type': 'acl_name',
                       # Cisco `aaa group server tacacs+ <name>` label.
                       # Default 'TACACS-GROUP' is what the template
                       # shipped before this knob existed. Per-scope
                       # override lets operators match site naming
                       # conventions (e.g. TACACS_PROD, ISE-GROUP).
                       # acl_name type enforces letter-start +
                       # [A-Za-z0-9_-] which is what IOS accepts.
                       'default': 'TACACS-GROUP'}),
    ('radius_group.', {'type': 'acl_name',
                       # The RADIUS twin of tacacs_group.<scope>: the
                       # Cisco `aaa group server radius <name>` label
                       # `config cisco --protocol radius` renders. Same
                       # naming rules, own default.
                       'default': 'RADIUS-GROUP'}),
    ('scope_auth_method.',
                      {'type': 'enum',
                       # The protocol a scope's devices and hosts use
                       # when the command is given none ('tacctl scope
                       # auth-method'): `config cisco|juniper` without
                       # --protocol, `host enroll` and `config linux
                       # script` without --method. No default here on
                       # purpose: an unset key means "not decided for
                       # this scope" (devices: tacacs; hosts:
                       # host.default_method), which an explicit
                       # 'tacacs' is not.
                       'values': ['tacacs', 'radius']}),
    # Per-scope mgmt-ACL overrides. These live under a separate
    # `scope_mgmt_acl.*` top-level namespace rather than extending
    # `mgmt_acl.*`, because the global `mgmt_acl.permits` is a list
    # and `mgmt_acl.names.{cisco,juniper}` are scalars — nesting
    # `<scope>` under either would require set_nested to silently
    # reshape list->dict / scalar->dict and wipe the global value.
    # The render code walks: scope_mgmt_acl.permits.<scope> ->
    # mgmt_acl.permits (global) -> shipped default, same for names.
    ('scope_mgmt_acl.names.cisco.',
                      {'type': 'acl_name', 'default': 'VTY-ACL'}),
    ('scope_mgmt_acl.names.juniper.',
                      {'type': 'acl_name', 'default': 'MGMT-ACL'}),
    # Default [] so an explicit empty list prunes the override and
    # renders fall through to the global `mgmt_acl.permits`.
    ('scope_mgmt_acl.permits.',
                      {'type': 'cidr_list', 'default': []}),
    # listeners.<backend>.<name>: two trailing segments, and the value is a
    # mapping (see _listener_py). Its default is per name, from
    # LISTENER_BACKENDS.
    ('listeners.',    {'type': 'listener', 'depth': 2}),
]

import re

CMD_RE = re.compile(r'^[a-zA-Z][a-zA-Z0-9 _-]+$')

def command_match_is_dead(name, rx):
    """True when a command-rule `match` regex can never match.

    tacquito's CommandBasedAuthorizer compares a rule's `name` to the
    TACACS+ cmd= word and then tests each `match` regex against the
    space-joined cmd-arg values ONLY (`show running-config` is tested
    as 'running-config'). A regex that begins with the command word
    itself -- `^show .*$`, `^ping( .*)?$`, `^show$` -- would only ever
    match an argument string that repeats the command, so the rule is
    dead and every invocation falls through to the next rule (usually
    the deny catch-all). Used at write time, by `group commands add`,
    and by the upgrade migration that heals older configs.
    """
    if not isinstance(name, str) or name == '*' or not isinstance(rx, str):
        return False
    body = rx[1:] if rx.startswith('^') else rx
    tail = r'(?:\s|\\s|\$|\((?:\?:)?(?:\s|\\s))'
    return re.match(re.escape(name) + tail, body) is not None

def schema_for(path):
    if path in SCHEMA:
        return SCHEMA[path]
    for prefix, rule in WILDCARDS:
        if not path.startswith(prefix):
            continue
        # Reject empty names (just the prefix itself, or an empty segment).
        parts = path[len(prefix):].split('.')
        if len(parts) == rule.get('depth', 1) and all(parts):
            return rule
    return None

def implicit_default(path):
    """Return the implicit per-instance default for a wildcard schema
    entry (e.g. aaa.order.<scope> -> 'tacacs-first'), or None if the path
    has no implicit default. Used by _conf_write's revert-to-default
    prune so operators can unset a wildcard override by re-setting it to
    the default value."""
    rule = schema_for(path)
    if rule is None:
        return None
    if rule['type'] == 'listener':
        _, backend, name = path.split('.')
        return (LISTENER_BACKENDS.get(backend) or {'defaults': {}})['defaults'].get(name)
    return rule.get('default')

def validate(path, value, is_list):
    """Return (ok: bool, msg: str). msg is empty on success."""
    rule = schema_for(path)
    if rule is None:
        return False, f"unknown config key (typo? path must be one of the known tunables)"
    t = rule['type']

    if is_list and t not in ('cidr_list', 'cisco_cmd_list', 'command_rules', 'backend_list'):
        return False, f"{t} does not accept list input; drop 'set-list'"
    if not is_list and t in ('cidr_list', 'cisco_cmd_list', 'command_rules', 'backend_list'):
        return False, f"{t} requires list input (use conf_set_list)"

    if t == 'int':
        if not isinstance(value, int) or isinstance(value, bool):
            return False, f"must be an integer"
        lo, hi = rule.get('min'), rule.get('max')
        if lo is not None and value < lo:
            return False, f"must be >= {lo}; got {value}"
        if hi is not None and value > hi:
            return False, f"must be <= {hi}; got {value}"
        return True, ''
    if t == 'nullable_string':
        if value is None:
            return True, ''
        if not isinstance(value, str):
            return False, f"must be a string or null"
        p = rule.get('pattern')
        if p and not re.match(p, value):
            return False, f"does not match required pattern {p!r}"
        return True, ''
    if t == 'enum':
        vals = rule.get('values') or []
        if not isinstance(value, str):
            return False, f"must be a string (one of: {', '.join(vals)})"
        if value not in vals:
            return False, f"must be one of: {', '.join(vals)} (got {value!r})"
        return True, ''
    if t == 'acl_name':
        # Cisco/Juniper ACL name shape; mirrors validate_acl_name's rules.
        if not isinstance(value, str):
            return False, f"must be a string"
        if not (1 <= len(value) <= 63):
            return False, f"must be 1..63 chars; got {len(value)}"
        if not re.match(r'^[A-Za-z][A-Za-z0-9_-]*$', value):
            return False, f"must start with a letter and contain only [A-Za-z0-9_-]"
        return True, ''
    if t == 'cidr_list':
        import ipaddress
        if not isinstance(value, list):
            return False, f"must be a list of CIDRs"
        for i, item in enumerate(value):
            if not isinstance(item, str):
                return False, f"element {i}: must be a string"
            try:
                ipaddress.ip_network(item, strict=False)
            except ValueError:
                return False, f"element {i}: {item!r} is not a valid CIDR"
        return True, ''
    if t == 'host_port':
        why = host_port_problem(value)
        return (not why), why
    if t == 'listener':
        _, backend, name = path.split('.')
        why = listener_problem(backend, name, value)
        return (not why), why
    if t == 'backend_list':
        vals = rule.get('values') or []
        if not isinstance(value, list) or not value:
            return False, f"must be a non-empty list of backends (known: {', '.join(vals)})"
        for i, item in enumerate(value):
            if item not in vals:
                return False, f"element {i}: {item!r} is not a backend (known: {', '.join(vals)})"
            if item in value[:i]:
                return False, f"element {i}: {item!r} is listed twice"
        return True, ''
    if t == 'cisco_cmd_list':
        if not isinstance(value, list):
            return False, f"must be a list of Cisco priv-exec command strings"
        for i, item in enumerate(value):
            if not isinstance(item, str):
                return False, f"element {i}: must be a string"
            if not CMD_RE.match(item):
                return False, f"element {i}: {item!r} has invalid characters (letters/digits/spaces/_/- only)"
            if len(item) > 64:
                return False, f"element {i}: too long ({len(item)} chars; max 64)"
        return True, ''
    if t == 'command_rules':
        # Per-group TACACS+ command authorization rules. Each entry is a
        # dict {name, action, match?}; the tail must be a "*" catch-all
        # whose action is the group's default. Regenerated into both
        # tacquito.yaml (for tacquito's command-authz) and Junos class
        # allow-commands / deny-commands.
        if not isinstance(value, list):
            return False, f"must be a list of rule dicts"
        if not value:
            return False, f"must not be empty (need at least a catch-all '*' rule)"
        name_re = re.compile(r'^([A-Za-z][A-Za-z0-9_-]{0,31}|\*)$')
        catchall_count = 0
        for i, item in enumerate(value):
            if not isinstance(item, dict):
                return False, f"element {i}: must be a dict {{name, action, match?}}"
            name = item.get('name')
            action = item.get('action')
            match = item.get('match', [])
            if not isinstance(name, str) or not name_re.match(name):
                return False, f"element {i}: name must be '*' or a letter-start token (got {name!r})"
            if name == '*':
                catchall_count += 1
                if i != len(value) - 1:
                    return False, f"element {i}: '*' catch-all must be the LAST rule"
            if action not in ('permit', 'deny'):
                return False, f"element {i}: action must be 'permit' or 'deny' (got {action!r})"
            if match is None:
                match = []
            if not isinstance(match, list):
                return False, f"element {i}: match must be a list of regex strings"
            for j, m in enumerate(match):
                if not isinstance(m, str):
                    return False, f"element {i}: match[{j}]: must be a string"
                try:
                    re.compile(m)
                except re.error as e:
                    return False, f"element {i}: match[{j}]: invalid regex ({e})"
                if command_match_is_dead(name, m):
                    return False, (f"element {i}: match[{j}]: {m!r} repeats the command word; "
                                   f"tacquito tests match regexes against the ARGUMENTS only "
                                   f"(e.g. 'running-config' for 'show running-config'), so this "
                                   f"rule can never match. Drop the '{name} ' prefix or omit match.")
            extra = set(item.keys()) - {'name', 'action', 'match'}
            if extra:
                return False, f"element {i}: unknown keys {sorted(extra)}"
        if catchall_count != 1:
            return False, f"must contain exactly one '*' catch-all rule (found {catchall_count})"
        return True, ''
    return False, f"unknown schema type {t!r}"
PY
}

# --- Write path -----------------------------------------------------------
# _conf_write: validate via schema, then load defaults (from
# conf_emit_defaults) + overrides, mutate via mode/path + optional scalar
# value or list-items-file, atomic-write. All value input arrives via argv
# or a temp file path, never via stdin — stdin belongs to the heredoc.
_conf_write() {
    local mode="$1" path="$2" value="${3:-}" items_file="${4:-}"
    mkdir -p "$(dirname "$TACCTL_OVERRIDES_FILE")"
    # shellcheck disable=SC2016
    python3 - <(conf_emit_defaults) "$TACCTL_OVERRIDES_FILE" "$mode" "$path" "$value" "$items_file" <<PY
$(_conf_schema_py)

import os, sys, tempfile, yaml
defaults_path, overrides_path, mode, path, value, items_file = sys.argv[1:7]

def load(p):
    if p and os.path.exists(p):
        try:
            with open(p) as f:
                return yaml.safe_load(f) or {}
        except Exception:
            return {}
    return {}

def get_nested(d, path):
    cur = d
    for part in path.split('.'):
        if not isinstance(cur, dict) or part not in cur:
            return None
        cur = cur[part]
    return cur

def set_nested(d, path, val):
    parts = path.split('.')
    cur = d
    for p in parts[:-1]:
        if not isinstance(cur.get(p), dict):
            cur[p] = {}
        cur = cur[p]
    cur[parts[-1]] = val

def unset_nested(d, path):
    parts = path.split('.')
    chain = [d]
    cur = d
    for p in parts[:-1]:
        if not isinstance(cur, dict) or p not in cur:
            return
        cur = cur[p]
        chain.append(cur)
    if isinstance(cur, dict) and parts[-1] in cur:
        del cur[parts[-1]]
    # Prune empty parent maps from the leaf upward.
    for i in range(len(parts) - 2, -1, -1):
        parent = chain[i]
        key = parts[i]
        if isinstance(parent.get(key), dict) and not parent[key]:
            del parent[key]

def coerce_scalar(s):
    # value comes in as a string (argv). Parse as int/bool/null when it
    # looks like one; else keep as-is. Empty string is preserved.
    if s == '':
        return ''
    try:
        return int(s)
    except ValueError:
        pass
    if '.' in s:
        try:
            return float(s)
        except ValueError:
            pass
    low = s.lower()
    if low == 'true':
        return True
    if low == 'false':
        return False
    if low == 'null':
        return None
    return s

# --- Validate BEFORE loading+mutating anything. ---
if mode == 'set':
    parsed = coerce_scalar(value)
    ok, msg = validate(path, parsed, is_list=False)
    if not ok:
        print(f"tacctl config: {path}: {msg}", file=sys.stderr)
        sys.exit(1)
elif mode == 'set_list':
    items = []
    if items_file and os.path.isfile(items_file):
        with open(items_file) as f:
            items = [line.rstrip('\n') for line in f if line.strip()]
    ok, msg = validate(path, items, is_list=True)
    if not ok:
        print(f"tacctl config: {path}: {msg}", file=sys.stderr)
        sys.exit(1)
elif mode == 'set_json':
    # value is a JSON payload (scalar, list, or dict). Parse + validate
    # as-is; the schema entry for <path> decides what's acceptable.
    import json
    try:
        parsed = json.loads(value) if value else None
    except json.JSONDecodeError as e:
        print(f"tacctl config: {path}: invalid JSON payload ({e})", file=sys.stderr)
        sys.exit(1)
    ok, msg = validate(path, parsed, is_list=isinstance(parsed, list))
    if not ok:
        print(f"tacctl config: {path}: {msg}", file=sys.stderr)
        sys.exit(1)
    if schema_for(path)['type'] == 'listener':
        # Stored without the keys that only repeat a default.
        parsed = listener_compact(path.split('.')[1], parsed)
elif mode == 'unset':
    pass  # unsetting an unknown key is a no-op, not an error.
else:
    print(f"_conf_write: bad mode {mode!r}", file=sys.stderr)
    sys.exit(2)

defaults = load(defaults_path)
overrides = load(overrides_path)

# Revert-to-default prune: compare the new value against the YAML
# defaults tree first, then fall back to the schema's implicit default
# (for wildcard paths like aaa.order.<scope> that aren't pre-enumerated
# in conf_emit_defaults).
def _default_for(p):
    v = get_nested(defaults, p)
    if v is not None:
        return v
    return implicit_default(p)

if mode == 'set':
    if _default_for(path) == parsed:
        unset_nested(overrides, path)
    else:
        set_nested(overrides, path, parsed)
elif mode == 'set_list':
    if _default_for(path) == items:
        unset_nested(overrides, path)
    else:
        set_nested(overrides, path, items)
elif mode == 'set_json':
    if _default_for(path) == parsed:
        unset_nested(overrides, path)
    else:
        set_nested(overrides, path, parsed)
elif mode == 'unset':
    unset_nested(overrides, path)

# A listener is also checked against the others: two on one network and
# address cannot both bind. Refused before anything is written.
if path.startswith('listeners.') and mode != 'unset':
    clash = listeners_problems(overrides, only=path)
    if clash:
        print(f"tacctl config: {clash[0]}", file=sys.stderr)
        sys.exit(1)

# Empty overrides dict -> remove the file entirely (no-overrides posture).
if not overrides:
    try:
        os.unlink(overrides_path)
    except FileNotFoundError:
        pass
    sys.exit(0)

tmp = tempfile.NamedTemporaryFile('w', dir=os.path.dirname(overrides_path) or '.', delete=False)
tmp.write("# tacctl overrides. Hand-edits are fine as long as the YAML stays\n")
tmp.write("# valid. View effective posture: 'tacctl config dump'.\n\n")
yaml.safe_dump(overrides, tmp, default_flow_style=False, sort_keys=False)
tmp.close()
os.chmod(tmp.name, 0o640)
os.rename(tmp.name, overrides_path)
PY
    local rc=$?
    # Ownership matches tacquito.yaml when we're installed; silent-fail in tests.
    chown tacquito:tacquito "$TACCTL_OVERRIDES_FILE" 2>/dev/null || true
    _conf_invalidate
    return $rc
}

